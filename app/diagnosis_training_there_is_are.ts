const defaultWrong = (correctAnswer: string): TriText => tri(
  `Не этот кусок. Здесь нужно "${correctAnswer}": проверяем слово после there.`,
  `Не цей шматок. Тут потрібно "${correctAnswer}": перевіряємо слово після there.`,
  `No es este bloque. Aquí necesitamos "${correctAnswer}": revisa la palabra después de there.`,
);

function step(input: {
  id: string;
  order: number;
  difficulty: DiagnosisTrainingStep['difficulty'];
  targetSkill: string;
  sentence: string;
  translation: TriText;
  explanationBlock: TriText;
  microTask?: TriText;
  options: string[];
  correctAnswerId: string;
  correctFeedback: TriText;
  wrongFeedbackByOption?: Record<string, TriText>;
  retryLine: string;
  fallbackExplanation?: TriText;
  focusWords: string[];
}): DiagnosisTrainingStep {
  return {
    id: input.id,
    order: input.order,
    difficulty: input.difficulty,
    type: 'single_choice',
    targetSkill: input.targetSkill,
    translation: input.translation,
    explanationBlock: input.explanationBlock,
    microTask: input.microTask ?? tri(
      'Выбери кусок, который нормально начинает эту фразу.',
      'Обери шматок, який нормально починає цю фразу.',
      'Elige el bloque que empieza la frase de forma natural.',
    ),
    sentence: input.sentence,
    answerOptions: input.options.map(option),
    correctAnswerId: input.correctAnswerId,
    correctIndex: input.options.findIndex((item) => item === input.correctAnswerId),
    correctFeedback: input.correctFeedback,
    wrongFeedbackByOption: Object.fromEntries(
      input.options
        .filter((item) => item !== input.correctAnswerId)
        .map((item) => [
          item,
          input.wrongFeedbackByOption?.[item] ?? defaultWrong(input.correctAnswerId),
        ]),
    ),
    retryFeedback: retry(input.retryLine),
    fallbackExplanation: input.fallbackExplanation ?? tri(
      'There is - для одной вещи или того, что не считаем по штукам. There are - для нескольких вещей. В вопросе: Is there / Are there.',
      'There is - для однієї речі або того, що не рахуємо по штуках. There are - для кількох речей. У питанні: Is there / Are there.',
      'There is para una cosa o algo que no contamos por unidades. There are para varias cosas. En pregunta: Is there / Are there.',
    ),
    focusWords: input.focusWords,
  };
}

