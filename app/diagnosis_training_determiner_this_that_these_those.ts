        id: 'This - untuk satu benda dekat. That - untuk satu benda jauh. These - untuk beberapa benda dekat. Those - untuk beberapa benda jauh.',
        tr: 'This - yakın tek nesne için. That - uzak tek nesne için. These - yakın birkaç nesne için. Those - uzak birkaç nesne için.',
