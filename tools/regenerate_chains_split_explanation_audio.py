def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def load_env(path: Path = Path(".env.local")) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8-sig", errors="ignore").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def capcut_is_open() -> bool:
    result = subprocess.run(
        ["tasklist", "/FI", "IMAGENAME eq CapCut.exe"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="ignore",
        check=False,
    )
    return "CapCut.exe" in result.stdout


def backup_project() -> Path:
    BACKUP_DIR.parent.mkdir(parents=True, exist_ok=True)
    if BACKUP_DIR.exists():
        shutil.rmtree(BACKUP_DIR)
    shutil.copytree(DRAFT_DIR, BACKUP_DIR)
    return BACKUP_DIR


def ffprobe_duration(path: Path) -> float:
    completed = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", str(path)],
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    return float(completed.stdout.strip())


def atempo_filter(factor: float) -> str:
    parts: list[str] = []
    while factor > 2.0:
        parts.append("atempo=2.0")
        factor /= 2.0
    while factor < 0.5:
        parts.append("atempo=0.5")
        factor /= 0.5
    parts.append(f"atempo={factor:.6f}")
    return ",".join(parts)


def normalize_wav(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            str(src),
            "-ac",
            "1",
            "-ar",
            "44100",
            "-c:a",
            "pcm_s16le",
            str(dst),
        ],
        check=True,
    )


def silence(path: Path, duration_sec: float) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-hide_banner",
            "-loglevel",
            "error",
            "-f",
            "lavfi",
            "-i",
            f"anullsrc=channel_layout=mono:sample_rate=44100",
            "-t",
            f"{duration_sec:.3f}",
            "-c:a",
            "pcm_s16le",
            str(path),
        ],
        check=True,
    )


def concat_wavs(paths: list[Path], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    concat_file = out.with_suffix(".concat.txt")
    concat_file.write_text(
        "".join(f"file '{path.resolve().as_posix()}'\n" for path in paths),
        encoding="utf-8",
    )
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-hide_banner",
            "-loglevel",
            "error",
            "-f",
            "concat",
            "-safe",
            "0",
            "-i",
            str(concat_file),
            "-ac",
            "1",
            "-ar",
            "44100",
            "-c:a",
            "pcm_s16le",
            str(out),
        ],
        check=True,
    )


def fit_to_slot(src: Path, mp3_out: Path, target_sec: float) -> dict[str, float]:
    raw = ffprobe_duration(src)
    fitted_wav = mp3_out.with_suffix(".slot.wav")
    if raw < target_sec:
        pad = mp3_out.with_name(mp3_out.stem + "_tail.wav")
        silence(pad, target_sec - raw)
        padded = mp3_out.with_name(mp3_out.stem + "_padded.wav")
        concat_wavs([src, pad], padded)
        src = padded
        raw = ffprobe_duration(src)
    factor = raw / target_sec if target_sec > 0 else 1.0
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            str(src),
            "-af",
            atempo_filter(factor),
            "-t",
            f"{target_sec:.6f}",
            "-ac",
            "1",
            "-ar",
            "44100",
            "-c:a",
            "pcm_s16le",
            str(fitted_wav),
        ],
        check=True,
    )
    mp3_out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            str(fitted_wav),
            "-c:a",
            "libmp3lame",
            "-b:a",
            "128k",
            str(mp3_out),
        ],
        check=True,
    )
    return {
        "raw_duration_sec": round(raw, 3),
        "target_duration_sec": round(target_sec, 3),
        "speed_factor": round(factor, 4),
    }


def classify_quoted_text(text: str) -> str:
    return "en" if re.search(r"[A-Za-z]", text) else "ru"


def split_voiceover(text: str) -> list[dict[str, str]]:
    chunks: list[dict[str, str]] = []
    pos = 0
    for match in re.finditer(r"«([^»]+)»", text):
        before = text[pos : match.start()].strip()
        if before:
            chunks.append({"lang": "ru", "text": before})
        quoted = match.group(1).strip()
        if quoted:
            chunks.append({"lang": classify_quoted_text(quoted), "text": quoted})
        pos = match.end()
    tail = text[pos:].strip()
    if tail:
        chunks.append({"lang": "ru", "text": tail})
    merged: list[dict[str, str]] = []
    for chunk in chunks:
        if merged and merged[-1]["lang"] == chunk["lang"]:
            merged[-1]["text"] = (merged[-1]["text"].rstrip() + " " + chunk["text"].lstrip()).strip()
        else:
            merged.append(chunk)
    return merged


def openai_tts(api_key: str, lang: str, text: str, out_wav: Path) -> None:
    if out_wav.exists() and out_wav.stat().st_size > 4096:
        return
    voice = OPENAI_RU_VOICE if lang == "ru" else OPENAI_EN_VOICE
    instructions = (
        "Speak Russian as a calm native Moscow-neutral teacher. Do not pronounce English."
        if lang == "ru"
        else "Speak native American English clearly and calmly for an A1 learner. No Russian accent."
    )
    payload = json.dumps(
        {
            "model": OPENAI_MODEL,
            "voice": voice,
            "input": text,
            "instructions": instructions,
            "response_format": "wav",
        },
        ensure_ascii=False,
    ).encode("utf-8")
    request = urllib.request.Request(
        "https://api.openai.com/v1/audio/speech",
        data=payload,
        headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=180) as response:
        out_wav.parent.mkdir(parents=True, exist_ok=True)
        out_wav.write_bytes(response.read())


def elevenlabs_tts(api_key: str, voice_id: str, lang: str, text: str, out_mp3: Path) -> None:
    if out_mp3.exists() and out_mp3.stat().st_size > 4096:
        return
    payload = {
        "text": text,
        "model_id": ELEVEN_MODEL,
        "language_code": "ru" if lang == "ru" else "en",
        "voice_settings": {
            "stability": 0.62 if lang == "ru" else 0.52,
            "similarity_boost": 0.78,
            "style": 0.08 if lang == "ru" else 0.03,
            "use_speaker_boost": True,
            "speed": 0.94 if lang == "ru" else 0.88,
        },
        "apply_text_normalization": "on",
    }
    response = requests.post(
        f"https://api.elevenlabs.io/v1/text-to-speech/{voice_id}?output_format=mp3_44100_128",
        headers={"xi-api-key": api_key, "Content-Type": "application/json"},
        data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
        timeout=180,
    )
    if response.status_code >= 400:
        raise RuntimeError(f"ElevenLabs TTS failed {response.status_code}: {response.text[:600]}")
    out_mp3.parent.mkdir(parents=True, exist_ok=True)
    out_mp3.write_bytes(response.content)


def generate_chunk(
    provider: str,
    env: dict[str, str],
    index: int,
    chunk_index: int,
    lang: str,
    text: str,
) -> Path:
    raw_dir = SPLIT_DIR / "chunks" / f"{index:02d}"
    raw = raw_dir / f"{chunk_index:02d}_{lang}_{provider}.wav"
    if raw.exists() and raw.stat().st_size > 4096:
        return raw
    if provider == "openai":
        try:
            openai_tts(env["OPENAI_API_KEY"], lang, text, raw)
            return raw
        except urllib.error.HTTPError as error:
            body = error.read().decode("utf-8", errors="replace")
            if "insufficient_quota" in body:
                raise RuntimeError("OPENAI_INSUFFICIENT_QUOTA") from error
            raise

    mp3 = raw.with_suffix(".mp3")
    ru_voice = env.get("ELEVENLABS_RU_EXPLANATION_VOICE_ID") or env.get("ELEVENLABS_RU_TIP_VOICE_ID") or env.get("ELEVENLABS_VOICE_ID") or ELEVEN_RU_VOICE
    en_voice = env.get("ELEVENLABS_EN_VOICE_1_ID") or ELEVEN_EN_VOICE
    elevenlabs_tts(env["ELEVENLABS_API_KEY"], ru_voice if lang == "ru" else en_voice, lang, text, mp3)
    normalize_wav(mp3, raw)
    return raw


def current_explanation_slots(draft: dict[str, Any]) -> list[dict[str, Any]]:
    track = next(t for t in draft["tracks"] if t.get("name") == "CODEx construction explanation UNIQUE VO")
    slots = []
    for segment in track["segments"]:
        slots.append(
            {
                "material_id": segment["material_id"],
                "duration_us": int(segment["target_timerange"]["duration"]),
                "duration_sec": int(segment["target_timerange"]["duration"]) / US,
            }
        )
    return slots


def update_audio_materials(draft: dict[str, Any], slots: list[dict[str, Any]]) -> None:
    audio_by_id = {item.get("id"): item for item in draft.get("materials", {}).get("audios", [])}
    for index, slot in enumerate(slots, start=1):
        material = audio_by_id.get(slot["material_id"])
        if not material:
            continue
        material["duration"] = slot["duration_us"]
        material["path"] = str(RESOURCE_AUDIO_DIR / f"{index:02d}_explanation.mp3")
        material["name"] = f"{index:02d}_explanation.mp3"
        material["wave_points"] = []


def planned_block_starts(item: dict[str, Any], chunks: list[dict[str, str]], target_sec: float) -> list[dict[str, Any]]:
    rough_char_sec = 0.065
    cursor = 0.0
    starts: dict[str, float] = {}
    for chunk in chunks:
        text = chunk["text"]
        if chunk["lang"] == "en":
            starts.setdefault(text.casefold(), cursor)
        cursor += max(0.85, len(text) * rough_char_sec)
        cursor += 0.12
    scale = target_sec / max(cursor, 0.1)
    timed_blocks = []
    for bi, block in enumerate(item.get("screen_blocks", [])):
        anchor = str(block.get("anchor_words", ""))
        raw_start = starts.get(anchor.casefold(), (target_sec * bi / max(1, len(item.get("screen_blocks", [])))) + 0.2)
        start = min(max(0.0, raw_start * scale), max(0.0, target_sec - 1.2))
        timed_blocks.append(
            {
                "text": block["text"],
                "anchor_words": anchor,
                "start_sec": round(start, 3),
                "end_sec": round(min(target_sec, start + 1.8), 3),
                "alignment_source": "split_ru_en_planned",
            }
        )
    return timed_blocks


def main() -> None:
    if capcut_is_open():
        raise SystemExit("CapCut is open. Close CapCut before regenerating split explanation audio.")

    env = load_env()
    if not env.get("ELEVENLABS_API_KEY") and not env.get("OPENAI_API_KEY"):
        raise RuntimeError("OPENAI_API_KEY or ELEVENLABS_API_KEY is required.")

    backup_path = backup_project()
    draft = read_json(CONTENT_PATH)
    timed = read_json(TIMED_PATH)
    slots = current_explanation_slots(draft)
    if len(slots) != len(timed):
        raise RuntimeError(f"slot count mismatch: {len(slots)} slots for {len(timed)} explanations")

    provider = "openai" if env.get("OPENAI_API_KEY") else "elevenlabs"
    provider_fallback_reason = ""
    manifest: list[dict[str, Any]] = []

    for index, item in enumerate(timed, start=1):
        target_sec = slots[index - 1]["duration_sec"]
        chunks = split_voiceover(str(item["voiceover"]))
        chunk_paths: list[Path] = []
        provider_used = "elevenlabs" if provider_fallback_reason == "openai_insufficient_quota" else provider
        for chunk_index, chunk in enumerate(chunks, start=1):
            try:
                path = generate_chunk(provider_used, env, index, chunk_index, chunk["lang"], chunk["text"])
            except RuntimeError as error:
                if str(error) != "OPENAI_INSUFFICIENT_QUOTA" or not env.get("ELEVENLABS_API_KEY"):
                    raise
                provider_used = "elevenlabs"
                provider_fallback_reason = "openai_insufficient_quota"
                path = generate_chunk(provider_used, env, index, chunk_index, chunk["lang"], chunk["text"])
            chunk_paths.append(path)
            gap = SPLIT_DIR / "chunks" / f"{index:02d}" / f"{chunk_index:02d}_gap.wav"
            silence(gap, 0.12)
            chunk_paths.append(gap)
        tail = SPLIT_DIR / "chunks" / f"{index:02d}" / "99_tail.wav"
        silence(tail, 0.55)
        chunk_paths.append(tail)

        raw_concat = SPLIT_DIR / "assembled" / f"{index:02d}_split_raw.wav"
        concat_wavs(chunk_paths, raw_concat)
        export_mp3 = EXPORT_AUDIO_DIR / f"{index:02d}_explanation.mp3"
        fit = fit_to_slot(raw_concat, export_mp3, target_sec)
        RESOURCE_AUDIO_DIR.mkdir(parents=True, exist_ok=True)
        shutil.copy2(export_mp3, RESOURCE_AUDIO_DIR / export_mp3.name)

        item["audio_path"] = str(export_mp3)
        item["duration_sec"] = round(target_sec, 3)
        item["tts_provider"] = f"{provider_used}_split_ru_en"
        item["audio_language_split"] = {
            "ru_chunks": sum(1 for chunk in chunks if chunk["lang"] == "ru"),
            "en_chunks": sum(1 for chunk in chunks if chunk["lang"] == "en"),
            "rule": "Russian narration and English quoted phrases are generated as separate audio chunks.",
        }
        item["timed_blocks"] = planned_block_starts(item, chunks, target_sec)
        manifest.append(
            {
                "index": index,
                "provider": item["tts_provider"],
                "fallback_reason": provider_fallback_reason,
                "target_sec": round(target_sec, 3),
                "fit": fit,
                "chunks": chunks,
            }
        )
        print(
            f"[split-explain-audio] {index:02d}/50 {item['tts_provider']} "
            f"target={target_sec:.2f}s speed={fit['speed_factor']:.3f}",
            flush=True,
        )
        write_json(TIMED_PATH, timed)
        write_json(ASSETS_DIR / "split_explanation_audio_manifest.partial.json", manifest)
        time.sleep(0.05)

    update_audio_materials(draft, slots)
    CONTENT_PATH.write_text(json.dumps(draft, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    if TMP_PATH.exists():
        TMP_PATH.write_text(json.dumps(draft, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    report = {
        "backup": str(backup_path),
        "provider_requested": provider,
        "provider_fallback_reason": provider_fallback_reason,
        "items": manifest,
    }
    write_json(ASSETS_DIR / "split_explanation_audio_manifest.json", report)
    print(json.dumps({"backup": str(backup_path), "items": len(manifest), "fallback": provider_fallback_reason}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
