function normalized(value) {
  return String(value ?? '').normalize('NFKC').trim().toLocaleLowerCase('und');
}

function legacyRows(legacyBank) {
  if (Array.isArray(legacyBank)) return legacyBank;
  if (Array.isArray(legacyBank?.rows)) return legacyBank.rows;
  throw new Error('Legacy French bank must contain a rows array');
}

function canonicalRowId(index) {
  return `fr-${String(index + 1).padStart(3, '0')}`;
}

function selectedTarget(row, index) {
  const override = FRENCH_SELECTION_OVERRIDES[canonicalRowId(index)];
  const legacyTarget = String(row?.targetText ?? row?.english).trim();
  if (!override) return legacyTarget;
  if (normalized(legacyTarget) !== normalized(override.legacyTargetText)) {
    throw new Error(`${canonicalRowId(index)} selection override no longer matches its frozen legacy target`);
  }
  return override.targetText;
}

function validateLegacySelection(rows) {
  if (rows.length !== REQUIRED_COUNT) {
    throw new Error(`Legacy French selection must contain exactly 176 rows; received ${rows.length}`);
  }

  const targets = new Set();
  const ids = new Set();
  rows.forEach((row, index) => {
    const expectedOrder = index + 1;
    if (row?.order !== expectedOrder) {
      throw new Error(`Legacy French selection must remain ordered 1..176; row ${index} has order ${String(row?.order)}`);
    }
    const target = normalized(selectedTarget(row, index));
    if (!target) throw new Error(`Legacy French row ${expectedOrder} has no targetText`);
    if (targets.has(target)) throw new Error(`Legacy French selection must contain unique targetText values; duplicate at order ${expectedOrder}`);
    targets.add(target);

    const id = normalized(row?.id);
    if (!id || ids.has(id)) throw new Error(`Legacy French selection must contain unique legacy ids; invalid row ${expectedOrder}`);
    ids.add(id);
  });

  FRENCH_AUTHORITATIVE_SOURCE_ROWS.forEach((sourceRow, index) => {
    const target = selectedTarget(rows[index], index);
    if (normalized(target) !== normalized(sourceRow.targetText)) {
      throw new Error(`Verified source row ${index + 1} does not match the selected French target`);
    }
  });
}

function legacyDraft(row) {
  return {
    sourceSchemaVersion: 'gustav-fr-daily-phrase-bank-v1',
    literal_ru: String(row?.literal ?? ''),
    meaning_ru: String(row?.meaning ?? ''),
    text_ru: String(row?.text ?? ''),
    literal_uk: String(row?.literal_uk ?? ''),
    meaning_uk: String(row?.meaning_uk ?? ''),
    text_uk: String(row?.text_uk ?? ''),
    reviewerStatus: row?.reviewerStatus ?? null,
    sourceEvidence: row?.sourceEvidence ?? null,
    sourceCoverage: row?.sourceCoverage ?? null,
  };
}

function scaffoldRow(row, index) {
  const id = canonicalRowId(index);
  const override = FRENCH_SELECTION_OVERRIDES[id];
  const scaffold = {
    id,
    order: index + 1,
    legacyId: String(row.id),
    studyTarget: 'fr',
    sourceLocale: 'ru',
    surface: 'daily_phrase',
    targetText: selectedTarget(row, index),
    targetExample: '',
    literal_ru: '',
    meaning_ru: '',
    text_ru: '',
    literal_uk: '',
    meaning_uk: '',
    text_uk: '',
    allowSave: true,
    active: false,
    activationApproved: false,
    candidateStatus: 'SOURCE_SCAFFOLD_HOLD',
    legacyDraft: legacyDraft(row),
  };
  if (override) {
    scaffold.selectionOverride = {
      legacyTargetText: override.legacyTargetText,
      replacementReason: override.replacementReason,
      conflictingRowId: override.conflictingRowId,
      legacyDraftScope: override.legacyDraftScope,
      currentSourceId: override.currentSourceId,
    };
  }
  return scaffold;
}

function authoredRowMatchesClosedScaffold(existing, scaffold) {
  return existing?.candidateStatus === 'CANDIDATE_PENDING_INDEPENDENT_REVIEW'
    && existing?.studyTarget === 'fr'
    && existing?.sourceLocale === 'ru'
    && existing?.surface === 'daily_phrase'
    && existing?.active === false
    && existing?.activationApproved === false
    && existing?.id === scaffold.id
    && existing?.order === scaffold.order;
}

function assertPreservableAuthoredRow(existing, scaffold) {
  const safe = authoredRowMatchesClosedScaffold(existing, scaffold)
    && normalized(existing?.targetText) === normalized(scaffold.targetText);
  if (!safe) throw new Error(`Existing authored row ${scaffold.id} violates the closed French scaffold contract`);
}

function isExplicitlySupersededAuthoredRow(existing, scaffold) {
  return authoredRowMatchesClosedScaffold(existing, scaffold)
    && scaffold?.selectionOverride?.legacyDraftScope === 'SUPERSEDED_HISTORICAL_RECORD_ONLY'
    && normalized(existing?.targetText) === normalized(scaffold.selectionOverride.legacyTargetText)
    && normalized(existing?.targetText) !== normalized(scaffold.targetText);
}

export function buildFrenchDailyPhraseScaffold({ legacyBank, existingBank = null, checkedAt }) {
  if (typeof checkedAt !== 'string' || !Number.isFinite(Date.parse(checkedAt))) {
    throw new Error('checkedAt must be an ISO-8601 timestamp');
  }

  const selectedRows = legacyRows(legacyBank);
  validateLegacySelection(selectedRows);
  const existingRows = Array.isArray(existingBank?.rows) ? existingBank.rows : [];
  const existingById = new Map(existingRows.map((row) => [String(row?.id ?? ''), row]));

  const rows = selectedRows.map((legacyRow, index) => {
    const scaffold = scaffoldRow(legacyRow, index);
    const existing = existingById.get(scaffold.id);
    if (existing?.candidateStatus !== 'CANDIDATE_PENDING_INDEPENDENT_REVIEW') return scaffold;
    if (isExplicitlySupersededAuthoredRow(existing, scaffold)) return scaffold;
    assertPreservableAuthoredRow(existing, scaffold);
    return existing;
  });

  const authoritativeRows = FRENCH_AUTHORITATIVE_SOURCE_ROWS.map((row) => ({
    ...row,
    checkedAt: row.checkedAt ?? checkedAt,
  }));
  const ledgerCheckedAt = authoritativeRows.reduce(
    (latest, row) => (Date.parse(row.checkedAt) > Date.parse(latest) ? row.checkedAt : latest),
    checkedAt,
  );
  const authoritativeLedger = {
    schemaVersion: 'daily-phrase-authoritative-source-ledger-v1',
    studyTarget: 'fr',
    source: SOURCE_TYPE,
    sourceHomes: [
      'https://dictionnaire.lerobert.com/',
      'https://www.larousse.fr/dictionnaires/francais/',
    ],
    checkedAt: ledgerCheckedAt,
    requiredCount: REQUIRED_COUNT,
    acceptedCount: authoritativeRows.length,
    status: 'SOURCE_PARTIAL_HOLD',
    rows: authoritativeRows,
  };

  const linkage = {
    schemaVersion: 'daily-phrase-source-linkage-v2',
    studyTarget: 'fr',
    sourceLocale: 'ru',
    surface: 'daily_phrase',
    status: 'SOURCE_PARTIAL_HOLD',
    authoritativeLedger: {
      path: AUTHORITATIVE_LEDGER_PATH,
      schemaVersion: authoritativeLedger.schemaVersion,
      source: SOURCE_TYPE,
      sourceHomes: authoritativeLedger.sourceHomes,
      checkedAt: ledgerCheckedAt,
      requiredCount: REQUIRED_COUNT,
      acceptedCount: authoritativeRows.length,
      status: 'SOURCE_PARTIAL_HOLD',
    },
    linkedCandidateRows: authoritativeRows.map((row, index) => ({
      rowId: `fr-${String(index + 1).padStart(3, '0')}`,
      ledgerRow: index,
      sourceId: row.sourceId,
    })),
    releasePolicy: 'Partial source linkage is not editorial approval. French Daily Phrase remains closed until all 176 rows and every independent hash-bound receipt pass.',
  };

  return {
    bank: {
      version: 1,
      schemaVersion: 'daily-phrase-target-source-bank-v1',
      studyTarget: 'fr',
      sourceLocale: 'ru',
      surface: 'daily_phrase',
      activationApproved: false,
      candidateStatus: 'HOLD',
      status: 'SOURCE_PARTIAL_HOLD',
      rows,
    },
    authoritativeLedger,
    linkage,
  };
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function writeJson(filePath, value) {
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

export function resolveFrenchSourceCheckedAt(requested, existingLedger = null, now = new Date()) {
  const explicit = String(requested ?? '').trim();
  if (explicit) {
    if (!Number.isFinite(Date.parse(explicit))) throw new Error('Explicit checkedAt must be an ISO-8601 timestamp');
    return explicit;
  }
  const frozen = String(existingLedger?.checkedAt ?? '').trim();
  if (frozen && Number.isFinite(Date.parse(frozen))) return frozen;
  return now.toISOString();
}

function runCli() {
  const legacyPath = path.resolve(
    process.cwd(),
    process.argv[2] || 'docs/gustav/runs/2026-07-04_fr_daily_phrases_production_v1/build/fr_daily_phrase_bank.json',
  );
  const outputDirectory = path.resolve(process.cwd(), process.argv[3] || 'content/daily-phrases/fr');
  const bankPath = path.join(outputDirectory, 'source-bank.json');
  const ledgerPath = path.join(outputDirectory, AUTHORITATIVE_LEDGER_PATH);
  const existingBank = fs.existsSync(bankPath) ? readJson(bankPath) : null;
  const existingLedger = fs.existsSync(ledgerPath) ? readJson(ledgerPath) : null;
  const checkedAt = resolveFrenchSourceCheckedAt(process.argv[4], existingLedger);
  const result = buildFrenchDailyPhraseScaffold({
    legacyBank: readJson(legacyPath),
    existingBank,
    checkedAt,
  });

  fs.mkdirSync(outputDirectory, { recursive: true });
  writeJson(bankPath, result.bank);
  writeJson(ledgerPath, result.authoritativeLedger);
  writeJson(path.join(outputDirectory, 'source-ledger.json'), result.linkage);
  console.log(JSON.stringify({
    status: result.bank.status,
    rows: result.bank.rows.length,
    verifiedSources: result.authoritativeLedger.acceptedCount,
    outputDirectory,
  }, null, 2));
}

const isDirectRun = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isDirectRun) runCli();
