import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(__dirname, '..');
const sourcePath = path.join(root, 'exports', 'lesson-theory-dump', 'lesson_theory_help.json');
const outputPath = path.join(root, 'functions', 'src', 'content_factory', 'english_theory_exemplars.generated.ts');

type Block = { type?: unknown; text?: unknown; title?: unknown };
type Lesson = { titleRU?: unknown; blocks?: unknown };
const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8')) as { lessons?: Record<string, Lesson> };
const stringValue = (value: unknown): string => typeof value === 'string' ? value.trim() : typeof value === 'object' && value !== null && typeof (value as { ru?: unknown }).ru === 'string' ? String((value as { ru: string }).ru).trim() : '';
const tagTokens = (value: string): string[] => [...new Set((value.normalize('NFKC').toLocaleLowerCase().match(/[a-zа-яё]{3,}/giu) ?? []).filter((token) => !['урок', 'lesson', 'этот', 'this'].includes(token)))].slice(0, 24);

const exemplars = Object.entries(source.lessons ?? {}).sort(([left], [right]) => Number(left) - Number(right)).map(([lessonId, lesson]) => {
  const blocks = Array.isArray(lesson.blocks) ? lesson.blocks as Block[] : [];
  const candidates = blocks.filter((block) => ['Body', 'Tip', 'Warn'].includes(String(block.type))).map((block) => stringValue(block.text)).filter((text) => text.length >= 25);
  if (!candidates.length) throw new Error(`theory_registry_lesson_empty:${lessonId}`);
  const title = stringValue(lesson.titleRU) || `Lesson ${lessonId}`;
  return {
    exemplarId: `english-lesson-${lessonId}`,
    ruleKey: `english-lesson-${lessonId}`,
    canonicalRule: candidates[0],
    objectiveTags: tagTokens(`${title} ${candidates.slice(0, 3).join(' ')}`),
    fragments: candidates.slice(0, 4).map((text, index) => ({ fragmentId: `english-lesson-${lessonId}-fragment-${index + 1}`, text })),
  };
});
if (exemplars.length < 32) throw new Error(`theory_registry_coverage_expected_32:${exemplars.length}`);
const registryHash = createHash('sha256').update(JSON.stringify(exemplars)).digest('hex');
const registry = { registryId: 'english-theory-core', version: 'v1', registryHash, source: 'app/lesson_help_theory_data.tsx', exemplars };
const output = `// Generated by scripts/build_content_factory_theory_registry.ts. Do not edit manually.\nexport const ENGLISH_THEORY_EXEMPLAR_REGISTRY = ${JSON.stringify(registry, null, 2)} as const;\n`;
fs.writeFileSync(outputPath, output, 'utf8');
console.log(JSON.stringify({ outputPath: path.relative(root, outputPath), exemplars: exemplars.length, registryHash }));
