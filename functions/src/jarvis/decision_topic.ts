import { createHash } from 'node:crypto';
import type { Decision } from './decision';

/**
 * Ключ ТЕМЫ решения — устойчивый адрес проблемы, не зависящий от сегодняшнего
 * значения счётчика.
 *
 * зачем этот модуль вообще существует (владелец 2026-08-15): жалобы «пишет
 * одно и то же» и «не учится» оказались одним классом бага. Почти каждый
 * `finding` содержит живое число («125 писем без ответа»). Любой ключ,
 * посчитанный от такого текста, назавтра становится другим — и система
 * считает вчерашнюю проблему новой:
 *   - память отказов не находит вчерашнее «нет» владельца;
 *   - дедупликация планов заводит второй план вместо обновления первого;
 *   - анти-повтор уведомлений видит новую тему.
 * Каждый из трёх механизмов написан правильно, но все трое адресуют тему
 * нестабильным ключом, поэтому не срабатывают.
 *
 * зачем отдельным модулем, а не копией в каждом файле: ключей темы в проекте
 * уже было два (`notificationTopicKey`, `rejectionTopicKey`), и они считались
 * по-разному. Третья копия сделала бы рассинхрон неизбежным: подавление в
 * одном канале срабатывало бы, в другом нет. Здесь один источник истины.
 *
 * зачем НЕ трогать `contentHash` (decision.ts): он обязан меняться вместе со
 * смыслом — на этом держится защита «одобрение старой версии больше не
 * действует». Тема и контент-хеш решают разные задачи и должны жить рядом.
 */

/** Длина ключа: 16 hex-символов — как у соседних ключей проекта. */
const TOPIC_KEY_LENGTH = 16;

/**
 * Схлопывает числа и пунктуацию, оставляя формулировку проблемы.
 *
 * зачем `#` вместо простого удаления: позиция числа в фразе сохраняется,
 * поэтому «3 платежа зависли, 12 подтверждены» и «12 платежей зависли,
 * 3 подтверждены» останутся разными темами — их различают слова вокруг чисел,
 * а не сами цифры.
 */
export function stripVolatileNumbers(value: string): string {
  return value
    .toLocaleLowerCase('ru')
    .replace(/\d[\d\s.,]*/g, '#')
    .replace(/[^\p{L}\p{N}#]+/gu, ' ')
    .trim();
}

/**
 * Адрес темы решения. Одна проблема — один ключ, сколько бы ни менялся счётчик.
 *
 * В ключ входят департамент, вопрос и нормализованные формулировки находки и
 * рекомендации: вопрос задаёт тему, находка и рекомендация отличают разные
 * проблемы внутри одного департамента.
 */
export function decisionTopicKey(decision: Decision): string {
  const material = [
    decision.department ?? '',
    stripVolatileNumbers(decision.question ?? ''),
    stripVolatileNumbers(decision.finding ?? ''),
    stripVolatileNumbers(decision.recommendation ?? ''),
  ].join('|');
  return createHash('sha256').update(material, 'utf8').digest('hex').slice(0, TOPIC_KEY_LENGTH);
}
