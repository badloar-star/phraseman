function makeStep(input: {
  id: string;
  order: number;
  difficulty: DiagnosisTrainingStep['difficulty'];
  targetSkill: string;
  sentence: string;
  translation: TriText;
  options: string[];
  correctAnswer: string;
  correctFeedback: TriText;
  wrong?: Record<string, TriText>;
  clue: TriText;
  finalHint: TriText;
  focusWords: string[];
}): DiagnosisTrainingStep {
  const fallbackWrong = defaultWrong(input.correctAnswer);

  return {
    id: input.id,
    order: input.order,
    difficulty: input.difficulty,
    type: 'single_choice',
    targetSkill: input.targetSkill,
    translation: input.translation,
    explanationBlock: tri(
      'Some и any нельзя выбирать только по переводу "какой-то". Сначала посмотри на ситуацию: обычное утверждение, вопрос, отрицание, предложение, просьба или свободный выбор.',
      'Some i any не можна обирати лише за перекладом "якийсь". Спочатку подивись на ситуацiю: звичайне твердження, питання, заперечення, пропозицiя, прохання або вiльний вибiр.',
      'Do not choose some/any by translation only. First look at the situation: statement, question, negative, offer, request, or free choice.',
    ),
    microTask: tri(
      'Выбери естественный кусок: some, any, no, something или anything.',
      'Обери природний шматок: some, any, no, something або anything.',
      'Choose the natural chunk: some, any, no, something, or anything.',
    ),
    sentence: input.sentence,
    answerOptions: input.options.map((text) => ({ id: text, text })),
    correctAnswerId: input.correctAnswer,
    correctIndex: input.options.findIndex((option) => option === input.correctAnswer),
    correctFeedback: input.correctFeedback,
    wrongFeedbackByOption: Object.fromEntries(
      input.options
        .filter((option) => option !== input.correctAnswer)
        .map((option) => [
          option,
          input.wrong?.[option] ??
            fallbackWrong[option] ??
            tri(
              'Почти, но здесь решает тип ситуации: утверждение, отрицание, вопрос, предложение или смысл "любой".',
              'Майже, але тут вирiшує тип ситуацiї: твердження, заперечення, питання, пропозицiя або сенс "будь-який".',
              `Almost. Use ${input.correctAnswer}.`,
            ),
        ]),
    ),
    retryFeedback: [
      input.clue,
      tri(
        'База такая: some - когда что-то есть или ты мягко предлагаешь/просишь. Any - в отрицаниях, нейтральных вопросах и смысле "любой".',
        'База така: some - коли щось є або ти мʼяко пропонуєш/просиш. Any - у запереченнях, нейтральних питаннях i значеннi "будь-який".',
        'Base rule: some for a positive amount or an offer/request. Any for negatives, neutral questions, and free choice.',
      ),
      tri(
        'Теперь проверь смысл: что-то есть, чего-то нет, мы спрашиваем, предлагаем или даем свободный выбор?',
        'Тепер перевiр сенс: щось є, чогось немає, ми питаємо, пропонуємо чи даємо вiльний вибiр?',
        input.finalHint.es,
      ),
      tri(
        'Здесь не надо переводить слово отдельно. Надо выбрать по ситуации целиком.',
        'Тут не треба перекладати слово окремо. Треба обрати за ситуацiєю цiлком.',
        `Answer: ${input.correctAnswer}.`,
      ),
    ],
    fallbackExplanation: tri(
      'Держи карту смысла: что-то есть или мягко предлагаем - some. Отрицание, нейтральный вопрос или выбор без ограничения - any.',
      'Тримай карту сенсу: щось є або мʼяко пропонуємо - some. Заперечення, нейтральне питання або вибір без обмеження - any.',
      "Chunks: I have some time. I don't have any money. Do you have any questions? Would you like some coffee? Choose any lesson.",
    ),
    focusWords: input.focusWords,
  };
}

