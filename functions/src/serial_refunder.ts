/**
 * Серийные возвращатели: когда возвраты одного человека становятся системой.
 *
 * зачем этот модуль (аудит 2026-08-16): админка УЖЕ помечает таких
 * покупателей (`legacy.html:24359`, фильтр «только серийные»), но никому об
 * этом не сообщает — владелец узнаёт, только если сам зайдёт и посмотрит.
 *
 * зачем отдельно от существующего алерта: `cancelRefundSpike` ловит ВСПЛЕСК
 * за час — много возвратов от разных людей сразу. Серийный возвращатель —
 * это один человек с двумя возвратами за месяцы, всплеска нет вообще.
 * Проверено чтением `admin_alerts.ts`: пороги и окна там про другое.
 *
 * Модуль чистый: без Firestore и сети, чтобы правила проверялись тестами.
 */

/**
 * Со скольких возвратов покупатель считается серийным.
 *
 * зачем два, а не «на глаз»: ровно так считает детектор в админке
 * (`r.serial = r.buyerCount >= 2`). Порог взят оттуда, а не выдуман —
 * иначе сигнал и список в панели показывали бы разных людей.
 */
export const SERIAL_REFUND_THRESHOLD = 2;

export function isSerialRefunder(refundCount: number): boolean {
  return Number.isFinite(refundCount) && refundCount >= SERIAL_REFUND_THRESHOLD;
}

export interface SerialRefunderAlertInput {
  readonly refundCount: number;
  /** Известен, но НЕ попадает в текст — см. ниже. */
  readonly buyerId?: string;
}

/**
 * Текст сигнала владельцу.
 *
 * зачем без идентификатора покупателя: правило проекта — во внешние каналы
 * уходят количества, не PII. Кто именно, видно в админке, где рядом с uid
 * показывается имя.
 */
export function buildSerialRefunderAlert(input: SerialRefunderAlertInput): string {
  return `🔁 <b>Серийные возвраты</b>\n\n`
    + `У одного покупателя уже ${input.refundCount} возврата.\n`
    + `Это не всплеск — это закономерность, и обычный алерт о всплеске её не ловит.\n\n`
    + `<i>Админка → Возвраты → фильтр «только серийные».</i>`;
}
