/** Длительность полёта одной частицы. */
export const REWARD_FLIGHT_MS = 620;
/**
 * Задержка между частицами — она же интервал между ударами счётчика.
 *
 * зачем 115, а не 55 (владелец, 2026-09-01: «он преувеличивается 1 раз, а
 * должен пульсировать с каждой руной»): счётчик бьёт на касание КАЖДОЙ
 * частицы, но при шаге 55мс следующий удар приходил ЗАДОЛГО до того, как
 * пружина успевала вернуть масштаб. Толчки склеивались в одно слитное
 * вздутие — снаружи это и выглядело как «увеличился один раз».
 *
 * 115мс — интервал, в который удар успевает отработать целиком (см. пружины
 * в HomeRewardCollectFlight: ~90мс вверх + ~налёт вниз). Полёт при этом
 * укорочен с 900 до 620мс, чтобы даже 14 частиц уложились в ~2.1с.
 */
export const REWARD_FLIGHT_STAGGER_MS = 115;
/** Хвост после приземления последней частицы — на вспышку счётчика. */
export const REWARD_FLIGHT_TAIL_MS = 120;

/** Сколько всего длится волна из N частиц — Главной нужен таймер-страховка. */
export function rewardFlightDurationMs(amount: number): number {
  const count = rewardFlightParticleCount(amount);
  if (count <= 0) return 0;
  return (
    REWARD_FLIGHT_MS
    + (count - 1) * REWARD_FLIGHT_STAGGER_MS
    + REWARD_FLIGHT_TAIL_MS
  );
}

/**
 * Точка старта частицы — ЗА краем экрана, по кругу вокруг цели.
 *
 * Углы раскладываются золотым углом: строгий веер выглядел бы машинно, а
 * Math.random дал бы разный кадр на каждый ре-рендер и невоспроизводимый тест.
 */
export function rewardFlightSpawnPoint(
  index: number,
  width: number,
  height: number,
  target: RewardFlightPoint,
): RewardFlightPoint {
  const golden = 2.399963229728653;
  const angle = index * golden + (index % 2 === 0 ? 0.32 : -0.18);
  // 0.9 диагонали, сжатие по вертикали 0.95.
  //
  // зачем именно столько: цель (счётчик) стоит НЕ в центре экрана, а в шапке,
  // поэтому радиус считается от неё, и «половины диагонали» не хватало —
  // при 0.62 часть частиц рождалась внутри кадра и вместо влёта из-за края
  // просто возникала на экране. Проверено тестом на пяти геометриях, включая
  // альбомную и счётчик у нижнего края.
  const radius = Math.hypot(width, height) * 0.9;
  return {
    x: target.x + Math.cos(angle) * radius,
    y: target.y + Math.sin(angle) * radius * 0.95,
  };
}
