// creator_access.ts — «Мастерская»: Free имеет утверждённые квоты, Plus
// получает расширенные квоты для своих карточек и наборов.
//
// Лимиты проверяются в write-boundary модулях: Free — 50 карточек / 3 набора,
// Plus — свои карточки и наборы без лимита (владелец 2026-09-30: «не 1500, а безлимит»).
//
// ГЛАВНОЕ ПРАВИЛО (решение владельца): уже созданное НЕ ОТБИРАЕТСЯ.
// Лимит действует только на создание нового. Смотреть, учить, редактировать и
// удалять свои старые карточки и наборы можно без подписки — иначе люди
// потеряли бы уже сделанную работу, а это волна возвратов и плохих отзывов.
// Поэтому здесь есть отдельная функция под создание и НЕТ функции «закрыть
// доступ к существующему» — её отсутствие намеренно.
// ═══════════════════════════════════════════════════════════════════════════

/** Что именно создаёт человек — от этого зависит текст пейвола. */
export type CreatorAction = 'card' | 'pack';

/**
 * Нужно ли показать пейвол на СОЗДАНИЕ нового.
 *
 * Гейт переиспользует фичу 'flashcards': у неё уже есть тумблер «Премиум/Фри»
 * в админ-пульте, поэтому владелец может открыть «Мастерскую» всем без релиза.
 *
 * зачем НЕ отдельная фича (подтверждено владельцем в аудите 2026-08-25): если
 * админ переведёт 'flashcards' в «Фри» — создание
 * откроется ВМЕСТЕ с тренировкой карточек, одним и тем же тумблером. Это
 * осознанный выбор, а не забытая связь: заводить отдельную фичу-флаг под одно
 * только создание владелец не попросил.
 */
export function shouldGateCreator(hasPremiumAccess: boolean): boolean {
  // Creation is available to Free users in 2.0; quota enforcement happens at
  // the write boundary (50 cards / 3 packs for Free; Plus is unlimited — D118).
  void hasPremiumAccess;
  return false;
}

/**
 * Контекст пейвола под каждое действие.
 *
 * зачем (владелец 2026-08-27, «показывается неправильный пейволл»): раньше сюда
 * переиспользовались чужие контексты ради экономии на словарях — карточка шла
 * как 'flashcard_limit' («20 из 20 — база собрана»), набор как
 * 'flashcard_training' («Тренировка карточек — в Plus»). Человек, который
 * просто нажал «создать», читал упрёк про исчерпанный лимит, которого он не
 * исчерпывал, либо рекламу режима, к которому не обращался. Теперь у каждого
 * действия свой контекст со своим честным текстом.
 */
export function creatorPaywallContext(action: CreatorAction): string {
  return action === 'pack' ? 'pack_create' : 'flashcard_create';
}

