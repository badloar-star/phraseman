function knownOperationIdsThroughLesson(lessonOrdinal: number): readonly string[] {
  return LEARNING_V2_ENGLISH_GRAMMAR_OPERATIONS_V1
    .filter((operation) => operation.lessonOrdinal <= lessonOrdinal)
    .map((operation) => operation.id);
}

function materializeChapterBlueprints(): readonly LearningV2EnglishChapterBlueprintV1[] {
  const chapters: LearningV2EnglishChapterBlueprintV1[] = [];

  for (let lessonOrdinal = 1; lessonOrdinal <= 32; lessonOrdinal += 1) {
    const seed = LESSON_SEEDS[lessonOrdinal];
    if (!seed) throw new Error(`learning_v2_chapter_seed_missing:${lessonOrdinal}`);

    const lessonOperations = LEARNING_V2_ENGLISH_GRAMMAR_OPERATIONS_V1.filter(
      (operation) => operation.lessonOrdinal === lessonOrdinal,
    );
    if (lessonOperations.length + seed.reviews.length !== 7) {
      throw new Error(`learning_v2_chapter_seed_count_invalid:${lessonOrdinal}`);
    }

    for (let chapterOrdinal = 1; chapterOrdinal <= 7; chapterOrdinal += 1) {
      const operation = lessonOperations[chapterOrdinal - 1] ?? null;
      const reviewSeed = seed.reviews[chapterOrdinal - lessonOperations.length - 1] ?? null;
      const primaryCanDoStep = operation?.communicativeFunction ?? reviewSeed?.canDo ?? "";
      const title = operation?.communicativeFunction ?? reviewSeed?.title ?? "";
      const reviewConstructIds = operation
        ? Object.freeze([] as string[])
        : Object.freeze([...knownOperationIdsThroughLesson(lessonOrdinal)]);

      chapters.push(Object.freeze({
        chapterId: `lesson-${String(lessonOrdinal).padStart(2, "0")}:chapter:${String(chapterOrdinal).padStart(2, "0")}`,
        lessonOrdinal,
        chapterOrdinal,
        title,
        primaryCanDoStep,
        grammarOperationId: operation?.id ?? null,
        reviewConstructIds,
        lexicalDomain: seed.lexicalDomain,
        lexicalMission: `Активировать лексику домена «${seed.lexicalDomain}» только в объёме, который нужен для шага: ${primaryCanDoStep}`,
        supportPlan: operation
          ? "Начать с ясного meaning-first примера, затем убрать опоры до самостоятельного применения в новой сцене."
          : "Начать сразу с retrieval изученных форм, сменить контекст и закончить независимым переносом без новой грамматики.",
        independentEvidence: `Без подсказки learner должен выполнить этот шаг в изменённой ситуации: ${primaryCanDoStep}`,
        sourceEvidenceRefs: EVIDENCE_REFS,
      }));
    }
  }

  return Object.freeze(chapters);
}

export const LEARNING_V2_ENGLISH_CHAPTER_BLUEPRINTS_V1 = materializeChapterBlueprints();
