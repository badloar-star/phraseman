    errors: list[str] = []
    if expected_count is not None and len(items) != expected_count:
        errors.append(f"expected {expected_count} descriptions, got {len(items)}")

    openings: dict[str, int] = {}
    normalized_texts: list[tuple[int, str]] = []
    for item in items:
        idx = int(item.get("chain_index") or item.get("index") or 0)
        text = clean_text(str(item.get("voiceover") or item.get("text") or ""))
        lower = text.casefold()
        token_list = words(text)
        word_count = len(token_list)

        if not text:
            errors.append(f"{idx:02d}: empty description")
            continue
        if LATIN_RE.search(text):
            errors.append(f"{idx:02d}: contains Latin/English characters")
        for banned in BANNED_ROOTS:
            if banned in lower:
                errors.append(f"{idx:02d}: banned description wording {banned!r}")
        if not (35 <= word_count <= 130):
            errors.append(f"{idx:02d}: word count {word_count} outside 35-130")
        if sum(1 for marker in STRUCTURE_MARKERS if marker in lower) < 2:
            errors.append(f"{idx:02d}: too little construction/grammar explanation")
        if not any(marker in lower for marker in HELP_MARKERS):
            errors.append(f"{idx:02d}: no learner-facing helper, image, check, or cultural hook")
        if text.count("?") > 2:
            errors.append(f"{idx:02d}: too many question marks")
        if re.search(r"\bсначала\b.{0,80}\bпотом\b.{0,80}\bзатем\b", lower):
            errors.append(f"{idx:02d}: mechanical sequence wording")
        opening = " ".join(token_list[:7]).casefold()
        if opening:
            if opening in openings:
                errors.append(f"{idx:02d}: repeated opening with {openings[opening]:02d}")
            openings[opening] = idx
        normalized_texts.append((idx, " ".join(token.casefold() for token in token_list)))

    for pos, (idx, text) in enumerate(normalized_texts):
        grams = set(zip(*(text.split()[i:] for i in range(4))))
        for other_idx, other in normalized_texts[pos + 1 :]:
            other_grams = set(zip(*(other.split()[i:] for i in range(4))))
            if not grams or not other_grams:
                ratio = SequenceMatcher(None, text, other).ratio()
            else:
                ratio = len(grams & other_grams) / max(1, len(grams | other_grams))
            if ratio > 0.30:
                errors.append(f"{idx:02d}/{other_idx:02d}: descriptions too similar ({ratio:.2f})")
                break

    return errors
