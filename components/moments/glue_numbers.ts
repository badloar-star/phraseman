// glue_numbers.ts — число не отрывается от соседнего слова при переносе строки (неразрывный пробел вместо обычного).
// зачем (координатор 18.10, проверка длинных языков pl/pt-BR/vi/uk/tr при шрифте 1,3 и 360 dp): «+10» оставался в конце строки, а «монет» уходило
// на следующую; Переводчик склеивал такие пары прямо в строках (c8ffad624), а строки моментов заморожены до 08:00. Поэтому склейка — на подстановке:
// функции текстов моментов прогоняют уже заполненную строку через glueNumbers. Сами тексты (копия) не меняются.
const NBSP = ' ';

/** «10 монет», «5. miejsce», «top 5», «— 1000» — пробел рядом с числом становится неразрывным. */
export function glueNumbers(text: string): string {
  return text
    .replace(/(\d\.?) (?=\S)/g, `$1${NBSP}`)
    .replace(/(\S) (?=[+−-]?\d)/g, `$1${NBSP}`);
}
