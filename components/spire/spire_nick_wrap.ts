// spire_nick_wrap.ts — точки переноса в длинном нике без пробелов («мокрый_асфальт»).
//
// зачем (координатор 13.10, строка 26 R1_BACKLOG): длинный ник без пробела на пьедестале рвался посреди слова. Мягкий перенос (U+200B, невидимый, не меняет
// ширину и копирование ника) ставим ПОСЛЕ «_», «.» и «-», если дальше идёт буква или цифра: перенос уходит на границу частей ника. Обрезки и ужатия нет —
// только перенос; часть, которая сама шире колонки, переносится системой как раньше. Только для показа: подписи для диктора и данные берут исходный ник.
// ═══════════════════════════════════════════════════════════════════════════

const ZWSP = '​';

export function spireNickWrap(name: string): string {
  if (!name) return name;
  return name.replace(/([_.-])(?=[^\s_.-])/g, `$1${ZWSP}`);
}
