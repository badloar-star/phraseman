#!/bin/bash
# Запуск команды с пределом времени: run_with_deadline.sh <секунды> <подпись> -- <команда…>
#
# зачем (владелец 11.11.2026, «да» на «выкладкам нужен предел ожидания»): выкладка двух функций
# Пика зависла на запросе к облаку Google без ответа и 34 минуты держала единственный слот
# светофора — очередь из восьми сессий стояла. Команда без предела времени висит молча.
#
# Код возврата команды пробрасывается как есть. Истекло время — код 124 и строка с причиной.
set -u
TAG="[DEADLINE]"

SEC="${1:-}"; LABEL="${2:-}"
if ! [[ "$SEC" =~ ^[0-9]+$ ]] || [ "$SEC" -lt 30 ] || [ "$SEC" -gt 3600 ]; then
  echo "$TAG ОТКАЗ: предел «$SEC» — нужно целое число секунд от 30 до 3600" >&2
  exit 2
fi
if [ -z "$LABEL" ] || [ "${3:-}" != "--" ] || [ $# -lt 4 ]; then
  echo "$TAG ОТКАЗ: формат — run_with_deadline.sh <секунды> <подпись> -- <команда…>" >&2
  exit 2
fi
shift 3

if ! command -v timeout >/dev/null 2>&1; then
  echo "$TAG ОТКАЗ: нет команды timeout (нужен Git Bash / coreutils) — без предела не запускаю «$LABEL»" >&2
  exit 2
fi

START=$(date +%s)
echo "$TAG «$LABEL»: предел $SEC с" >&2
# зачем --foreground: настоящая выкладка может задать вопрос в консоли и должна видеть ввод;
# -k 15: если процесс не завершился по сигналу, через 15 с снимается принудительно
timeout --foreground -k 15 "$SEC" "$@"
rc=$?
TOOK=$(( $(date +%s) - START ))
if [ $rc -eq 124 ] || [ $rc -eq 137 ]; then
  echo "$TAG ИСТЕКЛО ВРЕМЯ: «$LABEL» не завершилась за $SEC с (шла $TOOK с) — прервана" >&2
  exit 124
fi
echo "$TAG «$LABEL»: завершилась за $TOOK с, код $rc" >&2
exit $rc
