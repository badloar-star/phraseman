/** Что показываем вместо молчаливого ухода. Ни один вид не работает с ценами. */
export type SaveOfferKind =
  /** «Не пользуюсь» / «Временно» / «Дорого» → накопленный прогресс. */
  | 'progress'
  /** «Не хватает функций» / «Технические» → написать в поддержку. */
  | 'support'
  /** «Другое» и всё неизвестное → ничего не навязываем. */
  | 'none';

/** Локальный прогресс для варианта 'progress' (0 чтений Firestore). */
export type SaveOfferProgress = {
  readonly streak: number;
  readonly totalXP: number;
  readonly lessonsCompleted: number;
};

export type SaveOfferInput = {
  readonly reason: string | null;
  readonly progress: SaveOfferProgress | null;
};

/** Есть ли что показать в варианте 'progress' — пустой прогресс не мотивирует. */
export function hasMeaningfulProgress(progress: SaveOfferProgress | null): boolean {
  if (!progress) return false;
  return progress.streak > 0 || progress.totalXP > 0 || progress.lessonsCompleted > 0;
}

/**
 * Причина отмены → шаг удержания.
 *
 * Порядок веток намеренно консервативный: если подходящего предложения нет
 * (нечего показать, план не переключается), возвращаем 'none' и человек идёт
 * в магазин ровно как раньше. Пустой экран-заглушка «мы вас теряем» хуже, чем
 * его отсутствие, — он крадёт тап и ничего не даёт взамен.
 */
export function resolveSaveOffer(input: SaveOfferInput): SaveOfferKind {
  const reason = String(input.reason ?? '').trim();

  // «Дорого» здесь НАМЕРЕННО ведёт к прогрессу, а не к другому тарифу: цену
  // мы не обсуждаем совсем (решение владельца). Показываем, что человек уже
  // получил за свои деньги, и уходим, если показать нечего.
  if (reason === 'too_expensive' || reason === 'not_using' || reason === 'temporary') {
    return hasMeaningfulProgress(input.progress) ? 'progress' : 'none';
  }

  if (reason === 'missing_features' || reason === 'technical') {
    // Эти причины чинятся разговором: человек не «не хочет платить», он не
    // получил то, за что заплатил.
    return 'support';
  }

  return 'none';
}
