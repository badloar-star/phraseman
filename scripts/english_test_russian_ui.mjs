function defaultInstruction(question) {
  const key = `${question.skill}:${question.format}`;
  return DEFAULT_INSTRUCTION_BY_TASK[key] || 'Прочитай задание и выбери правильный ответ.';
}

function cleanEnglishStimulus(prompt) {
  const value = prompt.trim();
  const singleQuotedReading = value.match(
    /^Read:\s*'([\s\S]*)'\s+(?:What|Which|When|Where|Who|Why|How)\b[^?]*\?$/i,
  );
  if (singleQuotedReading) return singleQuotedReading[1];

  const curlyQuotedReading = value.match(
    /^Read:\s*“([\s\S]*)”\s+(?:What|Which|When|Where|Who|Why|How)\b[^?]*\?$/i,
  );
  if (curlyQuotedReading) return curlyQuotedReading[1];

  const quotedExercise = value.match(
    /^(?:Choose|Complete|Use|Repeat|In formal English, choose)[^:]*:\s*“([\s\S]*)”$/i,
  );
  if (quotedExercise) return quotedExercise[1];

  const withoutQuestion = value.replace(
    /([.!?”'])\s+(?:What|Which|When|Where|Who|Why|How)\b[^?]*\?$/i,
    '$1',
  ).trim();
  return withoutQuestion;
}

export function russianUiForQuestion(question) {
  const override = TASK_OVERRIDES[question.id] || {};
  return {
    scenarioRu: BEGINNER_SCENARIOS[question.id]
      || DEFAULT_SCENARIO_BY_SKILL[question.skill]
      || 'Задание',
    instructionRu: override.instructionRu || defaultInstruction(question),
    stimulus: Object.hasOwn(override, 'stimulus')
      ? override.stimulus
      : cleanEnglishStimulus(question.prompt),
  };
}
