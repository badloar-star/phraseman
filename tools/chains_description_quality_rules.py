def clean_text(text: str) -> str:
    return " ".join(str(text).strip().split())


def words(text: str) -> list[str]:
    return WORD_RE.findall(text)


def infer_category(chain: dict[str, Any]) -> str:
    final = clean_text(chain.get("foreign_steps", [""])[-1]).casefold()
    if "because" in final:
        return "cause"
    if "before" in final or "after" in final or "morning" in final or "noon" in final:
        return "time"
    if " in " in f" {final} " or " on " in f" {final} " or " at " in f" {final} ":
        return "place"
    if " to " in f" {final} ":
        return "direction"
    if " from " in f" {final} ":
        return "direction"
    if " for " in f" {final} ":
        return "purpose"
    if " by " in f" {final} " or " with " in f" {final} ":
        return "method"
    if any(token in final for token in ("politely", "carefully", "quickly", "slowly", "accidentally", "completely", "early")):
        return "manner"
    return "default"


