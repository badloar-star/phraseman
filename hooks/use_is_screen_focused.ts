import { useIsFocused } from '@react-navigation/native';

/**
 * Возвращает true, когда экран, в котором живёт компонент, ВИДИМ (на переднем
 * плане навигации). Главная причина существования хука — накопительная
 * деградация: native-stack в этом проекте держит экраны под верхним
 * смонтированными и активными (freezeOnBlur:false на корневом Stack), поэтому
 * бесконечные анимации/таймеры на «ушедших» экранах продолжают крутиться и
 * греть телефон. AppState ловит только сворачивание ВСЕГО приложения, но не
 * переход между экранами внутри него — для этого нужен именно фокус экрана.
 *
 * Безопасен вне навигационного контекста (модалки/оверлеи, рендер в тестах):
 * если NavigationContainer недоступен, useIsFocused бросает — мы перехватываем
 * и возвращаем true, чтобы поведение не ухудшалось (компонент просто остаётся
 * анимированным, как раньше).
 */
export function useIsScreenFocused(): boolean {
  try {
    return useIsFocused();
  } catch {
    return true;
  }
}
