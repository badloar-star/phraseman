/**
 * Момент ОДНОГО удара счётчика — доля от полной длительности волны.
 *
 * зачем один удар, а не серия (владелец 2026-09-01, выбран макет «Гибрид»
 * из docs/motion/reward-collect): удар на каждую частицу читался как тряска,
 * серия из 2-4 — как дребезг. Правильная схема, подтверждённая исследованием:
 * плотный залп частиц + ОДНА мягкая волна счётчика + докрутка числа.
 *
 * 0.65 — удар приходит ДО конца полёта, когда прилетело большинство частиц.
 * Это принципиально: счётчик, реагирующий после последней частицы, читается
 * как «интерфейс тормозит» (NN/g; тот же приём в разборе Codrops, где реакция
 * счётчика стартует на трети раньше конца полёта).
 */
export const REWARD_FLIGHT_HIT_AT = 0.65;

/** Длительность одного удара счётчика: подъём и возврат. */
export const REWARD_FLIGHT_HIT_UP_MS = 140;
export const REWARD_FLIGHT_HIT_DOWN_MS = 240;

/**
 * Докрутка числа.
 *
 * Число НЕ прыгает скачком и НЕ привязано к частицам поштучно — это две
 * независимые анимации, которые просто перекрываются во времени. Кривая
 * ease-out без перелёта: цифра, проскочившая финальное значение и вернувшаяся,
 * читается как ошибка.
 */
export const REWARD_FLIGHT_COUNT_MS = 620;

/** Длительность полёта одной частицы. */
export const REWARD_FLIGHT_MS = 540;
/**
 * Задержка между частицами.
 *
 * 38мс — плотный «хвост кометы»: частицы почти сливаются в поток, и залп
 * выглядит щедрым. Плотность больше НЕ влияет на счётчик (удар один на волну,
 * см. REWARD_FLIGHT_HIT_AT), поэтому её можно держать высокой.
 */
export const REWARD_FLIGHT_STAGGER_MS = 38;
/** Хвост после приземления последней частицы — на вспышку счётчика. */
export const REWARD_FLIGHT_TAIL_MS = 120;

/** Сколько всего длится волна из N частиц — Главной нужен таймер-страховка. */
export function rewardFlightDurationMs(amount: number): number {
  const count = rewardFlightParticleCount(amount);
  if (count <= 0) return 0;
  return (
    REWARD_FLIGHT_MS
    + (count - 1) * REWARD_FLIGHT_STAGGER_MS
    + REWARD_FLIGHT_TAIL_MS
  );
}

/**
 * Точка старта частицы — ЗА краем экрана, по кругу вокруг цели.
 *
 * Углы раскладываются золотым углом: строгий веер выглядел бы машинно, а
 * Math.random дал бы разный кадр на каждый ре-рендер и невоспроизводимый тест.
 */
export function rewardFlightSpawnPoint(
  index: number,
  width: number,
  height: number,
  target: RewardFlightPoint,
): RewardFlightPoint {
  const golden = 2.399963229728653;
  const angle = index * golden + (index % 2 === 0 ? 0.32 : -0.18);
  // 0.9 диагонали, сжатие по вертикали 0.95.
  //
  // зачем именно столько: цель (счётчик) стоит НЕ в центре экрана, а в шапке,
  // поэтому радиус считается от неё, и «половины диагонали» не хватало —
  // при 0.62 часть частиц рождалась внутри кадра и вместо влёта из-за края
  // просто возникала на экране. Проверено тестом на пяти геометриях, включая
  // альбомную и счётчик у нижнего края.
  const radius = Math.hypot(width, height) * 0.9;
  return {
    x: target.x + Math.cos(angle) * radius,
    y: target.y + Math.sin(angle) * radius * 0.95,
  };
}
