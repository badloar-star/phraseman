/**
 * Геометрия и счёт частиц для анимации сбора наград на Главной.
 *
 * зачем отдельным модулем без React/expo-image: это чистая арифметика, и её
 * обязан покрывать тест. Пока правило «сколько частиц» жило внутри компонента,
 * проверить его можно было только подняв всю графику — то есть на практике
 * никак, а именно это правило ломается тише всего («сделаем 1 руна = 1 частица»,
 * и джекпот спина в 2000 рун кладёт экран).
 */

/** Потолок частиц: выше начинается каша и просадка кадров на слабых телефонах. */
export const REWARD_FLIGHT_MAX_PARTICLES = 14;

/**
 * Сколько частиц показать за N единиц валюты.
 *
 * Решение владельца 2026-09-01: «фиксировано 8–14, логарифмически». Число
 * частиц НЕ равно сумме награды: мелкая награда обязана отличаться от крупной,
 * но джекпот не должен заваливать экран, поэтому шкала логарифмическая.
 */
export function rewardFlightParticleCount(amount: number): number {
  if (!Number.isFinite(amount) || amount <= 0) return 0;
  // Мелкая награда (1–3) показывается почти «поштучно»: там частиц и так мало,
  // а человек видит ровно то, что заработал.
  if (amount <= 3) return Math.max(3, Math.round(amount) + 2);
  // Коэффициенты подобраны так, чтобы шкала РАСТЯГИВАЛАСЬ до самых крупных
  // призов, а не упиралась в потолок уже на полусотне: 10 → 6, 50 → 8,
  // 500 → 12, 2000 (джекпот спина) → 14. Первый вариант давал 14 уже при 25 —
  // тогда обычная награда за урок выглядела бы как джекпот.
  const scaled = Math.round(2.2 + Math.log2(amount) * 1.1);
  return Math.min(REWARD_FLIGHT_MAX_PARTICLES, Math.max(5, scaled));
}

export interface RewardFlightPoint {
  readonly x: number;
  readonly y: number;
}

