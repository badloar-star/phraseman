import { useWindowDimensions } from 'react-native';

/**
 * Множитель системного шрифта — для высоты строки.
 *
 * В React Native системная настройка размера шрифта увеличивает `fontSize`, но
 * НЕ трогает `lineHeight`: он задаётся числом и остаётся прежним. Поэтому
 * пара вроде `fontSize: 22, lineHeight: 29` при полуторном системном шрифте
 * превращается в кегль 33 внутри строки высотой 29 — строки наезжают друг на
 * друга и обрезаются сверху и снизу. Заметно это только на устройстве с
 * включённым крупным шрифтом, то есть ровно у тех, кому он нужен.
 *
 * Высота строки, умноженная на этот множитель, сохраняет замысел вёрстки при
 * обычном размере и остаётся правильной при любом увеличении.
 *
 * Хук, а не `PixelRatio.getFontScale()`, намеренно: значение меняется, пока
 * приложение запущено, и экран должен перерисоваться.
 */
export function useArenaFontScale(): number {
  const { fontScale } = useWindowDimensions();
  return Number.isFinite(fontScale) && fontScale > 0 ? fontScale : 1;
}
