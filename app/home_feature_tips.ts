/** Ограничить счётчик повторов диапазоном наборов (0 = первый показ). */
export function clampHomeFeatureTipReplayCount(value: number): number {
    if (!Number.isFinite(value)) return 0;
    return Math.max(0, Math.min(HOME_FEATURE_TIPS_MAX_REPLAYS, Math.floor(value)));
}

export function clampHomeFeatureTipIndex(value: number, total: number): number {
    if (!Number.isFinite(value) || total <= 0) return 0;
    return Math.max(0, Math.min(total - 1, Math.floor(value)));
}

/** Собрать карточки для текущего показа: replayCount 0..5 → наборы №1..№6. */
export function buildHomeFeatureTips(lang: Lang, replayCount: number): HomeFeatureTip[] {
    const setIndex = clampHomeFeatureTipReplayCount(replayCount);
    return HOME_FEATURE_TIP_SEEDS.map((seed) => ({
        title: homeFeatureTipText(lang, seed.title),
        body: homeFeatureTipText(lang, seed.bodies[setIndex]),
        icon: seed.icon,
    }));
}

