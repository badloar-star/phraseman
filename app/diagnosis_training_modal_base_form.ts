function retryFor(pattern: string, fullAnswer: string, correctAnswer: string): [TriText, TriText, TriText, TriText] {
  return [
    tri(
      `Сначала найди слово-помощник. Здесь нужен готовый кусок: ${pattern}.`,
      `Спочатку знайди слово-помічник. Тут потрібен готовий шматок: ${pattern}.`,
      `Primero encuentra la palabra de ayuda. Aqui necesitas el bloque: ${pattern}.`,
    ),
    tri(
      'Не добавляй к действию хвост. Не нужен to, не нужна буква -s, не нужна прошлая форма.',
      'Не додавай до дії хвіст. Не потрібне to, не потрібна літера -s, не потрібна минула форма.',
      'No agregues una cola a la accion. No necesitas to, ni -s, ni la forma de pasado.',
    ),
    tri(
      `Собери фразу целиком: ${fullAnswer}`,
      `Збери фразу повністю: ${fullAnswer}`,
      `Arma la frase completa: ${fullAnswer}`,
    ),
    tri(
      `Почти подсказка: выбери "${correctAnswer}".`,
      `Майже підказка: обери "${correctAnswer}".`,
      `Casi pista: elige "${correctAnswer}".`,
    ),
  ];
}

function modalStep(input: StepInput): DiagnosisTrainingStep {
  const correctIndex = input.options.findIndex((option) => option === input.correctAnswer);
  const wrongFeedbackByOption = Object.fromEntries(
    input.options
      .filter((option) => option !== input.correctAnswer)
      .map((option) => [
        option,
        input.wrong[option] ?? tri(
          `Почти. "${option}" выглядит логично, но после слова-помощника нужен простой вариант: ${input.correctAnswer}.`,
          `Майже. "${option}" виглядає логічно, але після слова-помічника потрібен простий варіант: ${input.correctAnswer}.`,
          `Casi. "${option}" parece logico, pero despues de la palabra de ayuda necesitas la forma simple: ${input.correctAnswer}.`,
        ),
      ]),
  ) as Record<string, TriText>;

  return {
    id: input.id,
    order: input.order,
    difficulty: input.difficulty,
    type: 'single_choice',
    targetSkill: input.targetSkill,
    translation: input.translation,
    explanationBlock: explanation,
    microTask: tri(
      'Выбери действие после слова-помощника.',
      'Обери дію після слова-помічника.',
      'Elige la accion despues de la palabra de ayuda.',
    ),
    sentence: input.sentence,
    answerOptions: input.options.map((text) => ({ id: text, text })),
    correctAnswerId: input.correctAnswer,
    correctIndex,
    correctFeedback: input.correctFeedback,
    wrongFeedbackByOption,
    retryFeedback: retryFor(input.pattern, input.fullAnswer, input.correctAnswer),
    fallbackExplanation: tri(
      `Запомни короткую пару: ${input.pattern}. Слово-помощник уже сделало свою работу, поэтому действие не меняется.`,
      `Запам'ятай коротку пару: ${input.pattern}. Слово-помічник уже зробило свою роботу, тому дія не змінюється.`,
      `Recuerda el par corto: ${input.pattern}. La palabra de ayuda ya hizo su trabajo, por eso la accion no cambia.`,
    ),
    focusWords: input.focusWords,
  };
}

