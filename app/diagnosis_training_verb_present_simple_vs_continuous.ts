function defaultWrong(correct: string): TriText {
  return tri(
    `Почти. Сначала проверь маркер времени и смысл. Здесь лучше: ${correct}.`,
    `Майже. Спочатку перевір маркер часу і зміст. Тут краще: ${correct}.`,
    `Almost. Check the time marker and meaning first. Better here: ${correct}.`,
  );
}

function psPcStep(input: {
  id: string;
  order: number;
  difficulty: DiagnosisTrainingStep['difficulty'];
  targetSkill: string;
  sentence: string;
  translation: TriText;
  options: string[];
  correctAnswer: string;
  correctFeedback: TriText;
  wrong: Record<string, TriText>;
  focusWords: string[];
}): DiagnosisTrainingStep {
  return {
    id: input.id,
    order: input.order,
    difficulty: input.difficulty,
    type: 'single_choice',
    targetSkill: input.targetSkill,
    translation: input.translation,
    teachingText: MODEL,
    explanationBlock: MODEL,
    microTask: tri(
      'Выбери форму по смыслу: привычка/факт или действие сейчас.',
      'Обери форму за змістом: звичка/факт чи дія зараз.',
      'Choose by meaning: habit/fact or action now.',
    ),
    sentence: input.sentence,
    answerOptions: input.options.map((text) => ({ id: text, text })),
    correctAnswerId: input.correctAnswer,
    correctIndex: input.options.findIndex((option) => option === input.correctAnswer),
    correctFeedback: input.correctFeedback,
    wrongFeedbackByOption: Object.fromEntries(
      input.options
        .filter((option) => option !== input.correctAnswer)
        .map((option) => [option, input.wrong[option] ?? defaultWrong(input.correctAnswer)]),
    ),
    retryFeedback: retry(input.correctAnswer),
    fallbackExplanation: tri(
      'Смотри не на русский перевод, а на ситуацию. Обычная привычка или стабильный факт идут одной простой формой. Действие прямо сейчас или временная ситуация идут через am/is/are и -ing.',
      'Дивись не на український переклад, а на ситуацію. Звичка або стабільний факт ідуть однією простою формою. Дія просто зараз або тимчасова ситуація йдуть через am/is/are і -ing.',
      'Do not rely on translation. Habit, fact, schedule, taste, or opinion usually uses Present Simple. Action now or temporary situation usually uses Present Continuous.',
    ),
    focusWords: input.focusWords,
  };
}

