        vi: 'Bản đồ: and thêm ý, but đối lập, because nêu lý do, so nêu kết quả, if nêu điều kiện, when nêu thời gian, although nghĩa là mặc dù.',
        id: 'Peta: and menambah, but memberi kontras, because memberi alasan, so memberi hasil, if memberi syarat, when memberi waktu, although berarti meskipun.',
