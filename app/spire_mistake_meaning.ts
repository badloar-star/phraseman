// spire_mistake_meaning.ts — короткий смысл фразы для ошибки из Пика вместо целого текста вопроса.
// зачем (Сверка 24.10 через координатора): у заданий Пика в поле «значение» лежал весь вопрос («Вы хотите сказать: «…».
// Какую английскую реплику выберете?»), и строка «Моих ошибок» показывала его вместо смысла. Смысл — фраза в кавычках
// внутри вопроса; кавычек нет, а текст похож на вопрос — значения нет (строка показывает одну фразу, как задумано).
const QUOTED = /[«“"„]([^«»“”"„]{1,160})[»”"“]/u;

/** Смысл из текста задания Пика: фраза в кавычках; без кавычек — сам текст, если он не вопрос; иначе null. */
export function spireMistakeMeaningV1(raw: string | null | undefined): string | null {
  const text = String(raw ?? '').trim();
  if (!text) return null;
  const quoted = QUOTED.exec(text)?.[1]?.trim();
  if (quoted) return quoted;
  // зачем: короткая фраза без вопросительного хвоста — это и есть смысл (старые задания «переведи фразу»)
  return /[?？]\s*$/u.test(text) ? null : text;
}

export default function __RouteShim() { return null; }
