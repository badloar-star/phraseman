/**
 * Автоснятие объяснения, на которое жалуются.
 *
 * зачем этот модуль (аудит 2026-08-16): админка честно признаёт в
 * комментарии — «жалоба сама не отключает кэш: админ вручную жмёт „Убрать
 * из кэша“». То есть система знает, что объяснение плохое, но ждёт, пока
 * владелец зайдёт и нажмёт. До этого момента каждый следующий пользователь
 * получает то же самое объяснение, на которое уже пожаловались пятеро.
 *
 * зачем именно снятие, а не правка: удаление кэша не ломает ничего —
 * следующий запрос сгенерирует объяснение заново. Это дешёвая обратимая
 * операция, ровно та, которую можно доверить автоматике.
 *
 * Модуль чистый: без Firestore, чтобы правила проверялись тестами.
 */

/**
 * Сколько РАЗНЫХ пользователей должны пожаловаться.
 *
 * зачем это значение: константа с тем же именем и значением уже была
 * объявлена в `explain_reports.ts`, но нигде не использовалась — имя
 * обещало отклонение при пяти жалобах, а кода не было. Порог взят оттуда,
 * чтобы поведение совпало с тем, что задумывалось изначально.
 *
 * Считаются только уникальные пользователи: один человек не может добить
 * порог сам, это уже обеспечено картой reporters.
 */
export const REPORT_REJECT_THRESHOLD = 5;

export interface ShouldRetireInput {
  readonly reportCount: number;
  /** Кэш уже снят по этой же причине. */
  readonly alreadyRetired: boolean;
}

export function shouldRetireCache(input: ShouldRetireInput): boolean {
  // зачем проверка alreadyRetired: иначе каждая следующая жалоба слала бы
  // владельцу новый сигнал об одном и том же объяснении — ровно тот шум,
  // от которого перестают читать уведомления целиком.
  if (input.alreadyRetired) return false;
  if (!Number.isFinite(input.reportCount)) return false;
  return input.reportCount >= REPORT_REJECT_THRESHOLD;
}

export interface RetireAlertInput {
  readonly phraseEn: string;
  readonly reportCount: number;
  readonly lang: string;
}

/**
 * Сигнал владельцу о снятом объяснении.
 *
 * зачем говорить про перегенерацию: без этого «снято» читается как «фраза
 * сломана навсегда», и владелец идёт чинить то, что чинится само.
 */
export function buildRetireAlert(input: RetireAlertInput): string {
  const phrase = input.phraseEn.slice(0, 120);
  return `🧹 <b>Объяснение снято автоматически</b>\n\n`
    + `«${phrase}» (${input.lang})\n`
    + `Пожаловались ${input.reportCount} разных пользователей.\n\n`
    + `<i>Кэш очищен — следующий запрос сгенерирует объяснение заново. `
    + `Если проблема в самой фразе, а не в объяснении, это повторится.</i>`;
}
