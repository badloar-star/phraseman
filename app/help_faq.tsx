function FaqItem({ item, t, f, isUK }: { item: typeof FAQ_RU[0]; t: any; f: any; isUK: boolean }) {
  const [open, setOpen] = useState(false);
  const anim = useRef(new Animated.Value(0)).current;

  const toggle = () => {
    if (!open) {
      setOpen(true);
      Animated.timing(anim, { toValue: 1, duration: 220, useNativeDriver: false }).start();
    } else {
      Animated.timing(anim, { toValue: 0, duration: 180, useNativeDriver: false }).start(() => setOpen(false));
    }
  };

  return (
    <PremiumCard level={2} style={{ marginBottom: 10 }} innerStyle={{ padding: 0 }}>
      <TouchableOpacity
        activeOpacity={0.7}
        onPress={toggle}
        style={{ flexDirection: 'row', alignItems: 'center', padding: 16, gap: 12 }}
      >
        <Text style={{ fontSize: f.numMd }}>{item.icon}</Text>
        <Text style={{ flex: 1, fontSize: f.body, fontWeight: '600', color: t.textPrimary, lineHeight: f.body * 1.4 }}>
          {item.question}
        </Text>
        <Ionicons
          name={open ? 'chevron-up' : 'chevron-down'}
          size={18}
          color={t.textMuted}
        />
      </TouchableOpacity>
      {open && (
        <View style={{ paddingHorizontal: 16, paddingBottom: 16, borderTopWidth: 0.5, borderTopColor: t.border }}>
          <Text style={{ fontSize: f.sub, color: t.textSecond, lineHeight: f.sub * 1.7, marginTop: 14 }}>
            {item.answer}
          </Text>
        </View>
      )}
    </PremiumCard>
  );
}

