export function frenchLessonTitle(lessonId: number, sourceLocale: SourceLocale | Lang): string | undefined {
  const entry = frenchLessonCurriculumEntry(lessonId);
  if (!entry) return undefined;
  const titles: Partial<Record<SourceLocale | Lang, string>> = {
    ru: entry.titleRU,
    uk: entry.titleUK,
    'pt-BR': entry.titlePtBr,
    vi: entry.titleVi,
    id: entry.titleId,
    tr: entry.titleTr,
    pl: entry.titlePl,
  };
  const title = titles[sourceLocale];
  if (title) return title;
  const defaultTitle = entry.titleRU;
  return defaultTitle;
}

