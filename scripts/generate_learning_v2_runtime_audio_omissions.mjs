#!/usr/bin/env node
// Генератор app/learning_v2_runtime_audio_omissions_v1.generated.ts из content/learning-v2-course/activation/en/runtime-audio-omissions.v1.json.
//
// зачем (репетиция сборки 15.10, координатор): рантайм не должен импортировать JSON из content/ — .watchmanconfig исключает content
// целиком, и на чистой машине (сервер EAS) Metro не видел файл: «Unable to resolve …runtime-audio-omissions.v1.json», бандл не собирался.
// Данные переезжают в app/ как остальные *.generated.ts; источник истины прежний (фабрика Codex пишет JSON).
// Сторож tests/learning_v2_runtime_audio_omissions_generated.test.mjs: сгенерированное = JSON. Поменялся JSON → перезапустить генератор.
//
// node scripts/generate_learning_v2_runtime_audio_omissions.mjs          — записать
// node scripts/generate_learning_v2_runtime_audio_omissions.mjs --check  — только сверить (код 1 при расхождении)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE_REL = 'content/learning-v2-course/activation/en/runtime-audio-omissions.v1.json';
export const OUTPUT_REL = 'app/learning_v2_runtime_audio_omissions_v1.generated.ts';

export function renderRuntimeAudioOmissionsModule(sourceText) {
  const manifest = JSON.parse(sourceText);
  const sha = createHash('sha256').update(sourceText.replace(/\r\n/g, '\n')).digest('hex');
  return [
    '/* Generated by scripts/generate_learning_v2_runtime_audio_omissions.mjs — не править руками.',
    ` * Источник: ${SOURCE_REL} (sha256 ${sha}).`,
    ' * зачем: рантайм не импортирует JSON из content/ (на чистой машине Watchman его не видит — бандл EAS не собирался). */',
    '',
    `export const LEARNING_V2_RUNTIME_AUDIO_OMISSIONS_SOURCE_SHA256_V1 = '${sha}';`,
    '',
    `export const LEARNING_V2_RUNTIME_AUDIO_OMISSIONS_MANIFEST_V1: unknown = ${JSON.stringify(manifest, null, 2)};`,
    '',
  ].join('\n');
}

function main() {
  const sourceText = readFileSync(path.join(ROOT, SOURCE_REL), 'utf8');
  const next = renderRuntimeAudioOmissionsModule(sourceText);
  const outPath = path.join(ROOT, OUTPUT_REL);
  let current = null;
  try {
    current = readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n');
  } catch (error) {
    console.log(`[V2-OMISSIONS-GEN] ${OUTPUT_REL} не прочитан (${error instanceof Error ? error.message : String(error)}) — будет создан`);
  }
  if (process.argv.includes('--check')) {
    const same = current === next;
    console.log(`[V2-OMISSIONS-GEN] check: ${same ? 'совпадает' : 'РАСХОДИТСЯ — запусти генератор'}`);
    process.exitCode = same ? 0 : 1;
    return;
  }
  if (current === next) {
    console.log('[V2-OMISSIONS-GEN] без изменений');
    return;
  }
  writeFileSync(outPath, next, 'utf8');
  console.log(`[V2-OMISSIONS-GEN] записан ${OUTPUT_REL}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
