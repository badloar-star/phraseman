export function getLessonWordSourceLocaleGloss(
  english: string,
  locale: HeisenbergSourceLocale,
  pos?: string,
): string | undefined {
  const lower = english.trim().toLowerCase();
  if (pos) {
    const byPos = LESSON_WORD_SOURCE_LOCALES_BY_EN[`${lower}::${pos}`];
    if (byPos?.[locale]?.trim()) return byPos[locale];
  }
  const direct = LESSON_WORD_SOURCE_LOCALES_BY_EN[english];
  if (direct?.[locale]?.trim()) return direct[locale];
  const normalized = LESSON_WORD_SOURCE_LOCALES_BY_EN[lower];
  return normalized?.[locale]?.trim() || undefined;
}
