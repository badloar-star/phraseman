import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const file = path.join(root, "sessions", "en", "l02", "s15", "practice.atomic.json");
const substitutions = new Map([
  ["мужчина в костюме, который сидит идеально", "Макс в костюме, который сидит идеально"],
  ["чоловік у костюмі, який сидить бездоганно", "Макс у костюмі, який сидить бездоганно"],
  ["за столиком мужчина, на которого оборачиваются", "за столиком Макс, на которого оборачиваются"],
  ["за столиком чоловік, на якого озираються", "за столиком Макс, на якого озираються"],
  ["она красивая?", "Мира красивая?"],
  ["вона гарна?", "Міра гарна?"],
  ["спутник ест уже второй сэндвич, спросите, голоден ли он", "Макс ест уже второй сэндвич; спросите, голоден ли он"],
  ["супутник їсть уже другий сендвіч, запитайте, чи він голодний", "Макс їсть уже другий сендвіч; запитайте, чи він голодний"],
  ["спутник третий раз тянется к воде", "Макс третий раз тянется к воде"],
  ["супутник утретє тягнеться до води", "Макс утретє тягнеться до води"],
  ["женщина в изящном платье", "Мира в изящном платье"],
  ["жінка у вишуканій сукні", "Міра у вишуканій сукні"],
]);

const source = fs.readFileSync(file, "utf8");
const updated = [...substitutions].reduce((text, [from, to]) => text.split(from).join(to), source);
if (updated === source) throw new Error("l02/s15 actor repair made no change");
JSON.parse(updated);
fs.writeFileSync(file, updated, "utf8");
