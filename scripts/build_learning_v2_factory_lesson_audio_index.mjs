#!/usr/bin/env node
import fs from "node:fs";
import { loadRuntimeAudioSelection } from "./learning_v2_storage_audio_plan.mjs";
import path from "node:path";

const root = process.cwd();
const check = process.argv.includes("--check");
// Решение владельца 18.10: индекс включает используемый звук всех занятий,
// независимо от того, лежит он в первых пяти сессиях бандла или в Storage.
const selectionPath = process.argv.includes("--selection")
  ? process.argv[process.argv.indexOf("--selection") + 1]
  : path.join(root, "scripts/learning_v2_runtime_audio_selection.v1.json");
loadRuntimeAudioSelection(root, selectionPath);
const selection = JSON.parse(fs.readFileSync(selectionPath, "utf8"));
const lessons = {};
for (let i = 0; i < selection.ceiling; i += 1) {
  const lesson = Math.floor(i / 56) + 1, session = i % 56 + 1;
  lessons[lesson] ??= { sessionCount: 0, sessionOrdinals: [], sessions: {}, contentHashes: [] };
  lessons[lesson].sessionCount += 1;
  lessons[lesson].sessionOrdinals.push(session);
  lessons[lesson].sessions[session] = { contentHashes: [] };
}
for (const [hash, references] of Object.entries(selection.required)) {
  for (const reference of references) {
    const match = /^l(\d{2})s(\d{2})$/.exec(reference);
    if (!match) throw new Error("Invalid session reference: " + reference);
    const lesson = lessons[Number(match[1])], session = lesson?.sessions[Number(match[2])];
    if (!session) throw new Error("Audio reference outside current course: " + reference);
    session.contentHashes.push(hash);
  }
}
for (const lesson of Object.values(lessons)) {
  for (const session of Object.values(lesson.sessions)) session.contentHashes = [...new Set(session.contentHashes)].sort();
  lesson.contentHashes = [...new Set(Object.values(lesson.sessions).flatMap(session => session.contentHashes))].sort();
}
console.log("[V2-PREWARM-INDEX] referenced sessions=" + selection.ceiling + " files=" + Object.keys(selection.required).length);
const outputPath = path.join(root, "app/learning_v2_factory_lesson_audio_index_v1.generated.ts");
const lines = [
  "/* Generated by scripts/build_learning_v2_factory_lesson_audio_index.mjs. */",
  "export const LEARNING_V2_FACTORY_LESSON_AUDIO_INDEX_V1 = Object.freeze({",
  ...Object.entries(lessons).map(([lessonOrdinal, value]) =>
    `  ${lessonOrdinal}: Object.freeze({ sessionCount: ${value.sessionCount}, sessionOrdinals: Object.freeze(${JSON.stringify(value.sessionOrdinals)}), sessions: Object.freeze({${Object.entries(value.sessions).map(([sessionOrdinal, session]) => `${sessionOrdinal}: Object.freeze({ contentHashes: Object.freeze(${JSON.stringify(session.contentHashes)}) })`).join(",")}}), contentHashes: Object.freeze(${JSON.stringify(value.contentHashes)}) }),`),
  "} as const);",
  "",
];
const next = lines.join("\n");
// зачем (координатор 18.10, красный сторож «лёгкий срез озвучки совпадает с полным индексом»): срез правили руками
// (553cbf47b), и после каждого переноса уроков он отставал. Теперь его пишет и проверяет этот же проход — разойтись нельзя.
const slicePath = path.join(root, "app/learning_v2_published_audio_sessions_v1.generated.ts");
const sliceNext = [
  "/* Generated by scripts/build_learning_v2_factory_lesson_audio_index.mjs.",
  " * Лёгкий срез learning_v2_factory_lesson_audio_index_v1.generated.ts:",
  " * только список озвученных занятий, без хэшей (те весят сотни КБ и нужны",
  " * лишь при запуске занятия). Позволяет проверить «есть ли озвучка» без",
  " * разбора полного индекса при открытии раздела.",
  " *",
  " * зачем: аудит 20.09 замерил — открытие раздела держало JS-тред 2612 мс,",
  " * а сам вопрос «есть ли у занятия озвучка» — это список номеров на 1 КБ.",
  " * Источник истины прежний; расхождение ловит сторож карты Learning V2. */",
  "export const LEARNING_V2_PUBLISHED_AUDIO_SESSIONS_V1: Readonly<Record<number, readonly number[]>> = Object.freeze({",
  ...Object.entries(lessons).map(([lessonOrdinal, value]) => `  ${lessonOrdinal}: Object.freeze(${JSON.stringify(value.sessionOrdinals)}),`),
  "});",
  "",
].join("\n");
if (check) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== next)
    throw new Error("learning_v2_factory_lesson_audio_index_stale");
  if (!fs.existsSync(slicePath) || fs.readFileSync(slicePath, "utf8").replace(/\r\n/g, "\n") !== sliceNext)
    throw new Error("learning_v2_published_audio_sessions_slice_stale");
  console.log(`factory lesson audio index PASS (${Object.keys(lessons).length} published lesson packs, slice in sync)`);
} else {
  fs.writeFileSync(outputPath + ".tmp", next, "utf8");
  fs.renameSync(outputPath + ".tmp", outputPath);
  fs.writeFileSync(slicePath + ".tmp", sliceNext, "utf8");
  fs.renameSync(slicePath + ".tmp", slicePath);
  console.log(`wrote ${path.relative(root, outputPath)} + ${path.relative(root, slicePath)} (${Object.keys(lessons).length} published lesson packs)`);
}
