import { createHash } from 'node:crypto';
import { access, cp, mkdir, readFile, readdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';

const args = process.argv.slice(2);
const valueFor = (name) => { const index = args.indexOf(name); return index < 0 ? undefined : args[index + 1]; };
const fail = (reason) => { throw new Error(`avatar_publish_invalid: ${reason}`); };
const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');
const exists = async (file) => access(file).then(() => true).catch(() => false);

async function verifyReceipt(sourceDir, receipt, version) {
  if (!receipt || receipt.receiptVersion !== 1 || receipt.assetVersion !== version || !Array.isArray(receipt.files) || receipt.files.length === 0) fail('receipt');
  for (const file of receipt.files) {
    if (!file || typeof file.file !== 'string' || path.basename(file.file) !== file.file || !file.file.endsWith('.webp') || !Number.isInteger(file.bytes) || !/^[a-f0-9]{64}$/.test(file.sha256)) fail('receipt file');
    const buffer = await readFile(path.join(sourceDir, file.file));
    if (buffer.length !== file.bytes || sha256(buffer) !== file.sha256) fail('hash or bytes mismatch');
    const metadata = await sharp(buffer).metadata();
    const expectedSize = file.file === 'thumbnail.webp' ? 192 : 512;
    if (metadata.format !== 'webp' || metadata.width !== expectedSize || metadata.height !== expectedSize) fail('webp dimensions');
  }
}

const requirePath = (modulePath, assetPath) => {
  let relative = path.relative(path.dirname(modulePath), assetPath).replaceAll('\\', '/');
  if (!relative.startsWith('.')) relative = `./${relative}`;
  return relative;
};

export async function publishAssets({ version, source, target, catalogPath, bundledTarget, generatedModule }) {
  if (!Number.isInteger(version) || version < 1 || !source || !target) fail('arguments');
  const catalog = catalogPath ? JSON.parse(await readFile(catalogPath, 'utf8')) : null;
  const catalogItems = new Map((catalog?.items ?? []).map((item) => [item.id, item]));
  const bundledEntries = [];
  const itemNames = (await readdir(source)).sort();
  let published = 0; let replayed = 0;
  for (const itemId of itemNames) {
    const itemRoot = path.join(source, itemId);
    if (!(await stat(itemRoot)).isDirectory()) continue;
    const sourceDir = path.join(itemRoot, String(version));
    const receiptPath = path.join(sourceDir, 'receipt.json');
    const receipt = JSON.parse(await readFile(receiptPath, 'utf8'));
    if (receipt.itemId !== itemId) fail('item path mismatch');
    await verifyReceipt(sourceDir, receipt, version);
    const targetDir = path.join(target, itemId, String(version));
    if (await exists(targetDir)) {
      for (const file of [...receipt.files.map((entry) => entry.file), 'receipt.json']) {
        const left = await readFile(path.join(sourceDir, file));
        const right = await readFile(path.join(targetDir, file)).catch(() => null);
        if (!right || !left.equals(right)) fail('immutable overwrite');
      }
      replayed += 1;
    } else {
      await mkdir(targetDir, { recursive: true });
      for (const file of receipt.files) await cp(path.join(sourceDir, file.file), path.join(targetDir, file.file), { errorOnExist: true, force: false });
      await cp(receiptPath, path.join(targetDir, 'receipt.json'), { errorOnExist: true, force: false });
      published += 1;
    }
    const catalogItem = catalogItems.get(itemId);
    if (catalogItem?.entitlement?.kind === 'free' && bundledTarget && generatedModule) {
      const bundleDir = path.join(bundledTarget, itemId, String(version));
      await mkdir(bundleDir, { recursive: true });
      for (const layer of catalogItem.layers ?? []) {
        const sourceFile = path.join(sourceDir, layer.file);
        const targetFile = path.join(bundleDir, layer.file);
        if (await exists(targetFile)) {
          const [left, right] = await Promise.all([readFile(sourceFile), readFile(targetFile)]);
          if (!left.equals(right)) fail('immutable bundled overwrite');
        } else {
          await cp(sourceFile, targetFile, { errorOnExist: true, force: false });
        }
        bundledEntries.push({ key: `${itemId}:${version}:${layer.file}`, file: targetFile });
      }
    }
  }
  if (generatedModule && bundledTarget) {
    const lines = bundledEntries.sort((left, right) => left.key.localeCompare(right.key)).map((entry) => `  ${JSON.stringify(entry.key)}: require(${JSON.stringify(requirePath(generatedModule, entry.file))}),`);
    await mkdir(path.dirname(generatedModule), { recursive: true });
    await import('node:fs/promises').then(({ writeFile }) => writeFile(generatedModule, `/* generated by scripts/avatar-dna/publish_assets.mjs */\nexport const BUNDLED_AVATAR_DNA_ASSETS = {\n${lines.join('\n')}\n} as const;\n`));
  }
  return { published, replayed };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  publishAssets({ version: Number(valueFor('--version')), source: valueFor('--source'), target: valueFor('--target'), catalogPath: valueFor('--catalog'), bundledTarget: valueFor('--bundled-target'), generatedModule: valueFor('--generated-module') })
    .then(({ published, replayed }) => console.log(`avatar-dna publish: PASS (published=${published}, replayed=${replayed})`))
    .catch((error) => { console.error(error instanceof Error ? error.message : 'avatar_publish_invalid'); process.exitCode = 1; });
}
