/** Металл ранга; вне диапазона — ближайший край (ранг приходит с сервера, доверять нельзя). */
export function coinMetalForRank(rank: number): CoinMetal {
  const safe = Number.isFinite(rank) ? Math.round(rank) : 0;
  const idx = Math.max(0, Math.min(COIN_METALS.length - 1, safe)); // guard-ok: индекс палитры цвета, не баланс
  return COIN_METALS[idx];
}
