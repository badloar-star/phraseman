/**
 * Ищет процедуру по описанию симптома.
 *
 * зачем не подгонять под первую попавшуюся: выдать неподходящую процедуру
 * хуже, чем не выдать никакой — она уводит расследование в сторону, причём
 * с тем же видом уверенности.
 */
export function findPlaybook(symptom: string): Playbook | null {
  const text = symptom.trim().toLowerCase();
  if (!text) return null;
  for (const p of PLAYBOOKS) {
    if (p.triggers.some((t) => text.includes(t))) return p;
  }
  return null;
}

export function renderPlaybook(playbook: Playbook): string {
  const steps = playbook.steps
    .map((s, i) => `${i + 1}. ${s.check}\n   → ${s.meaning}`)
    .join('\n');
  return `${playbook.title}\n\nКогда: ${playbook.symptom}\n\n${steps}\n\nБыло раньше: ${playbook.precedent}`;
}
