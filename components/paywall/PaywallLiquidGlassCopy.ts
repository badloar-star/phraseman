const locales: Record<Lang, readonly string[]> = {
  ru, en, uk,
  es, 'pt-BR': ptBR, vi, id, tr, pl,
};

export function getLiquidPaywallCopy(lang: Lang): Record<LiquidCopyKey, string> {
  const values = locales[lang] ?? en;
  if (values.length !== keys.length) throw new Error(`paywall_copy_length:${lang}:${values.length}/${keys.length}`);
  return Object.fromEntries(keys.map((key, index) => [key, values[index]])) as Record<LiquidCopyKey, string>;
}
