#!/usr/bin/env python3
"""Regenerate Chains explanation voiceovers with separate RU/EN voices.

OpenAI TTS is the preferred provider, but the current project key can be out of
quota. In that case this script falls back to ElevenLabs while preserving the
important invariant: Russian narration is never asked to pronounce English
phrases. English phrases inside guillemets are generated by a native EN voice,
then all chunks are concatenated and fitted to the existing CapCut audio slot so
the user's edited timeline layout does not move.
"""

