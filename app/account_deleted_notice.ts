// ════════════════════════════════════════════════════════════════════════════
// account_deleted_notice.ts — плашка «Вы удалили все свои данные» на первом
// экране онбординга после удаления аккаунта.
//
// зачем: подтверждение удаления нельзя показывать алертом. Алерт — нативный
// <Modal>, а он презентуется в тот же кадр, в котором закрывается модалка
// подтверждения; на iOS это ломает стек презентаций (экран настроек остаётся
// на месте, тапы мертвы, онбординг не появляется) — тот самый фриз, который мы
// и чиним. Плашка же рисуется ВНУТРИ уже смонтированного онбординга, без
// present/dismiss.
//
// Состояние держим в памяти, а НЕ в AsyncStorage: удаление аккаунта делает
// AsyncStorage.clear(), и запись туда гонялась бы с очисткой. Онбординг
// монтируется в том же процессе сразу по событию account_deleted, так что
// память переживает переход гарантированно. Если процесс всё-таки убьют до
// показа — плашка просто не покажется, а это косметика: удаление к тому
// моменту уже необратимо зафиксировано замком в SecureStore.
// ════════════════════════════════════════════════════════════════════════════

/** Сколько плашка висит на экране, прежде чем уехать. */
export const ACCOUNT_DELETED_NOTICE_DURATION_MS = 3_000;

/**
 * Ключи онбординга, которые обязаны быть сняты ДО показа первого экрана.
 *
 * зачем: полный AsyncStorage.clear() при удалении аккаунта живёт в фоновой фазе,
 * а онбординг монтируется сразу и при монтировании восстанавливает сохранённый
 * шаг. Без снятия этих ключей пользователь после удаления попадал в середину
 * старого флоу (или не видел онбординг вовсе) вместо чистого первого экрана.
 * Значения обязаны совпадать с константами в CleanOnboarding.tsx — держим их
 * здесь, чтобы обе стороны читали один источник и рассинхрон не повторился.
 */
export const ONBOARDING_RESET_KEYS_ON_ACCOUNT_DELETE = [
  'onboarding_flow_version_v1',
  'onboarding_step',
  'onboarding_done',
] as const;

let noticePending = false;

/** Помечает, что на ближайшем экране онбординга надо показать плашку. */
export function markAccountDeletedNoticePending(): void {
  noticePending = true;
}

/**
 * Забирает пометку (одноразово): вернёт true ровно один раз после удаления.
 * Онбординг вызывает это при монтировании.
 */
export function consumeAccountDeletedNotice(): boolean {
  if (!noticePending) return false;
  noticePending = false;
  return true;
}

/** Только для тестов: сброс состояния между кейсами. */
export function resetAccountDeletedNoticeForTests(): void {
  noticePending = false;
}

/* expo-router route shim: keeps utility module from warning when discovered as route */
export default function __RouteShim() { return null; }
