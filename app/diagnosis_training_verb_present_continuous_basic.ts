function pcStep(input: {
  id: string;
  order: number;
  difficulty: DiagnosisTrainingStep['difficulty'];
  targetSkill: string;
  sentence: string;
  translation: TriText;
  options: string[];
  correctAnswer: string;
  correctFeedback: TriText;
  wrong?: Record<string, TriText>;
  fallbackExplanation: TriText;
  focusWords: string[];
}): DiagnosisTrainingStep {
  return {
    id: input.id,
    order: input.order,
    difficulty: input.difficulty,
    type: 'single_choice',
    targetSkill: input.targetSkill,
    translation: input.translation,
    teachingText: PC_MODEL,
    explanationBlock: PC_MODEL,
    microTask: tri(
      'Выбери форму для действия, которое происходит сейчас.',
      'Обери форму для дії, яка відбувається зараз.',
      'Choose the form for an action happening now.',
      {
        'pt-BR': 'Escolha a forma para uma ação acontecendo agora.',
        vi: 'Chọn dạng cho một hành động đang xảy ra bây giờ.',
        id: 'Pilih bentuk untuk aksi yang sedang terjadi sekarang.',
        tr: 'Şu anda olan bir eylem için doğru biçimi seç.',
        pl: 'Wybierz formę dla czynności dziejącej się teraz.',
      },
    ),
    sentence: input.sentence,
    answerOptions: input.options.map((text) => ({ id: text, text })),
    correctAnswerId: input.correctAnswer,
    correctIndex: input.options.findIndex((option) => option === input.correctAnswer),
    correctFeedback: input.correctFeedback,
    wrongFeedbackByOption: Object.fromEntries(
      input.options
        .filter((option) => option !== input.correctAnswer)
        .map((option) => [option, input.wrong?.[option] ?? defaultWrong(input.correctAnswer)]),
    ),
    retryFeedback: retry(input.correctAnswer),
    fallbackExplanation: input.fallbackExplanation,
    focusWords: input.focusWords,
  };
}

