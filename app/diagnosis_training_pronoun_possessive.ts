function retryFor(pattern: string, fullAnswer: string, correctAnswer: string): [TriText, TriText, TriText, TriText] {
  return [
    tri(
      `Сначала посмотри вправо от пропуска. Твой ориентир: ${pattern}.`,
      `Спочатку подивись праворуч від пропуску. Твій орієнтир: ${pattern}.`,
      `Primero mira a la derecha del hueco. Tu guia: ${pattern}.`,
    ),
    tri(
      'Если после пропуска сразу есть предмет, выбирай короткое слово. Если предмета после нет, выбирай слово, которое стоит одно.',
      'Якщо після пропуску одразу є предмет, обирай коротке слово. Якщо предмета після немає, обирай слово, яке стоїть саме.',
      'Si despues del hueco viene la cosa, elige la palabra corta. Si no viene la cosa, elige la palabra que va sola.',
    ),
    tri(
      `Собери фразу целиком: ${fullAnswer}`,
      `Збери фразу повністю: ${fullAnswer}`,
      `Arma la frase completa: ${fullAnswer}`,
    ),
    tri(
      `Почти подсказка: выбери "${correctAnswer}".`,
      `Майже підказка: обери "${correctAnswer}".`,
      `Casi pista: elige "${correctAnswer}".`,
    ),
  ];
}

function possessiveStep(input: StepInput): DiagnosisTrainingStep {
  const correctIndex = input.options.findIndex((option) => option === input.correctAnswer);
  const wrongFeedbackByOption = Object.fromEntries(
    input.options
      .filter((option) => option !== input.correctAnswer)
      .map((option) => [
        option,
        input.wrong[option] ?? tri(
          `Почти. "${option}" не подходит именно в этом месте. Проверь, есть ли предмет сразу после пропуска.`,
          `Майже. "${option}" не підходить саме в цьому місці. Перевір, чи є предмет одразу після пропуску.`,
          `Casi. "${option}" no encaja en este lugar. Mira si hay una cosa justo despues del hueco.`,
        ),
      ]),
  ) as Record<string, TriText>;

  return {
    id: input.id,
    order: input.order,
    difficulty: input.difficulty,
    type: 'single_choice',
    targetSkill: input.targetSkill,
    translation: input.translation,
    explanationBlock: sharedExplanation,
    microTask: tri(
      'Выбери слово для значения "чей / чья / чьё / чьи".',
      'Обери слово для значення "чий / чия / чиє / чиї".',
      'Elige la palabra para decir de quien es.',
    ),
    sentence: input.sentence,
    answerOptions: input.options.map((text) => ({ id: text, text })),
    correctAnswerId: input.correctAnswer,
    correctIndex,
    correctFeedback: input.correctFeedback,
    wrongFeedbackByOption,
    retryFeedback: retryFor(input.pattern, input.fullAnswer, input.correctAnswer),
    fallbackExplanation: tri(
      `Запомни короткую пару: ${input.pattern}. Если справа есть предмет, слово стоит перед ним. Если предмета справа нет, слово заменяет весь кусок.`,
      `Запам'ятай коротку пару: ${input.pattern}. Якщо праворуч є предмет, слово стоїть перед ним. Якщо предмета праворуч немає, слово замінює весь шматок.`,
      `Recuerda el par corto: ${input.pattern}. Si a la derecha hay una cosa, la palabra va antes. Si no hay cosa a la derecha, la palabra reemplaza todo el bloque.`,
    ),
    focusWords: input.focusWords,
  };
}

