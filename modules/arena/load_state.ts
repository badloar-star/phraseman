/**
 * Состояние загрузки экрана — одно на всю Арену.
 *
 * Существует из-за одной конкретной лжи, которая была на трёх экранах сразу:
 * при НЕУДАЧНОЙ загрузке они показывали «пусто». Игрок читал «матчей пока
 * нет» и «друзей нет» там, где на самом деле не ответил сервер. Это хуже
 * ошибки: ошибку он бы перечитал, а «пусто» принял за правду о себе.
 *
 * Отдельная ложь была на экране рангов: он рисовал «Бронза III · 0 очков» до
 * ответа сервера и при отказе — то есть показывал чужой ранг как свой.
 *
 * Владелец (D-65): «каждый интерфейс Арены продуман до конца». Четыре
 * состояния и есть та самая продуманность: пока не знаем — не утверждаем.
 */

export type ArenaLoadState =
  /** Ответа ещё нет. Показывать данные нельзя: их нет. */
  | 'loading'
  /** Ответ не пришёл. Это НЕ пустота — предложить повтор. */
  | 'failed'
  /** Ответ пришёл, данных в нём нет. Вот это и есть пустота. */
  | 'empty'
  | 'ready';

export function arenaLoadState(input: Readonly<{
  loaded: boolean;
  failed: boolean;
  count: number;
}>): ArenaLoadState {
  // Порядок важен: отказ важнее пустоты, иначе неудачная загрузка снова
  // прикинется отсутствием данных.
  if (input.failed) return 'failed';
  if (!input.loaded) return 'loading';
  return Math.max(0, Math.trunc(Number(input.count) || 0)) > 0 ? 'ready' : 'empty';
}

/** Можно ли показывать сами данные. */
export function arenaShowsData(state: ArenaLoadState): boolean {
  return state === 'ready';
}

/**
 * Можно ли показывать данные, у которых нет понятия «пусто».
 *
 * Ранг, кошелёк, профиль — у них не бывает пустого состояния, но бывает
 * неизвестное. До ответа сервера рисовать нули нельзя: ноль это утверждение,
 * а мы ещё ничего не знаем.
 */
export function arenaKnowsValue(input: Readonly<{ loaded: boolean; failed: boolean }>): boolean {
  return input.loaded && !input.failed;
}
