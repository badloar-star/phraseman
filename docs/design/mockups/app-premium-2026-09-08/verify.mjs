import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const dir = path.dirname(fileURLToPath(import.meta.url));
const html = fs.readFileSync(path.join(dir, 'standalone.html'), 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script, 'Inline application script exists');
new vm.Script(script, { filename: 'standalone.html' });
assert.ok(!/@@\w+@@/.test(html), 'All assets embedded');
assert.ok(!/(?:src|href)=["']https?:|url\(["']?https?:|\bfetch\(|XMLHttpRequest|WebSocket/.test(html), 'No external runtime dependencies or requests');
const screenBlock = script.match(/const screens=\[([\s\S]*?)\n\];/)?.[1];
const ids = [...screenBlock.matchAll(/^ \['([^']+)'/gm)].map(match => match[1]);
assert.equal(ids.length, 14);
assert.equal(new Set(ids).size, 14);
assert.ok(!ids.some(id => /max/i.test(id)));
assert.ok(script.includes("2800,false"), 'Feedback lifetime independent of reduced motion');
assert.ok(script.includes("state.pearls-=p.pearls"), 'Demo pearl spending updates pearl balance');
assert.ok(script.includes("escapeText(card[0])") && script.includes("escapeText(card[1])"), 'User-created practice text escaped');
console.log('PASS: JavaScript syntax, 14 unique screens, embedded assets, no network dependencies, no Max screen, focused state guards.');
