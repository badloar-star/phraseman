/**
 * Процедуры расследования: что проверять и в каком порядке.
 *
 * зачем этот модуль (аудит 2026-08-16): когда что-то ломается, модель
 * начинает свободно бродить по данным и находит первое, что похоже на
 * причину. Похожее на причину и причина — разные вещи, а уверенность
 * в ответе одинаковая.
 *
 * зачем записанные шаги: индустриальная практика — агент идёт по процедуре,
 * а не импровизирует. В разборе Meta агент проследил падение метрики до
 * конкретного деплоя именно потому, что шаг «проверь деплои за N часов» был
 * записан заранее, а не придуман на ходу.
 *
 * Три процедуры выбраны не наугад: посчитано по истории правок проекта за
 * три месяца — контракты 76 упоминаний, кэш 35, деплой 20. Турниры лидируют
 * по числу правок, но владелец распорядился их законсервировать, поэтому
 * процедуры под них не писались.
 *
 * Модуль чистый: без Firestore, чтобы правила проверялись тестами.
 */

export interface PlaybookStep {
  /** Что конкретно посмотреть. */
  readonly check: string;
  /** Какой вывод следует из увиденного. */
  readonly meaning: string;
}

export interface Playbook {
  readonly id: string;
  readonly title: string;
  /** Как это выглядит снаружи — по этому и опознаётся. */
  readonly symptom: string;
  /** Слова, по которым процедура находится. */
  readonly triggers: readonly string[];
  /** Реальный случай из истории проекта. */
  readonly precedent: string;
  readonly steps: readonly PlaybookStep[];
}

