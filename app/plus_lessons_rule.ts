/** Откат одной строкой: false — Plus снова идёт по прежней последовательной матрице (2★ за предыдущий, старты 9/19/29). */
export const PLUS_OPENS_ALL_LESSONS = true;

/** Открыт ли урок классического курса у человека с Plus (все 32, если правило включено). Тариф здесь не проверяется. */
export function plusOpensLesson(lessonId: number): boolean {
  return PLUS_OPENS_ALL_LESSONS && isMainCourseLesson(lessonId);
}

