export function PaywallContextIcon({ ctx, size, color }: {
  ctx: PremiumContext;
  size: number;
  color: string;
}) {
  const els = CONTEXT_ICON[ctx] ?? CONTEXT_ICON.generic;
  return (
    <Svg width={size} height={size} viewBox="0 0 48 48">
      {els.map((el, i) => {
        const stroke = el.t !== 'l' && el.fill ? 'none' : color;
        const fill = el.t !== 'l' && el.fill ? color : 'none';
        const common = {
          stroke,
          fill,
          strokeWidth: el.t === 'p' ? (el.w ?? 3.2) : 3.2,
          strokeLinecap: 'round' as const,
          strokeLinejoin: 'round' as const,
          opacity: el.o ?? 1,
        };
        // guard-ok: массив элементов иконки статичен (никогда не вставляется/не сортируется),
        // индексный key безопасен — при смене ctx перерендеривается весь Svg.
        if (el.t === 'p') return <Path key={i} d={el.d} {...common} />; // guard-ok
        if (el.t === 'c') return <Circle key={i} cx={el.cx} cy={el.cy} r={el.r} {...common} />; // guard-ok
        if (el.t === 'r') return <Rect key={i} x={el.x} y={el.y} width={el.w} height={el.h} rx={el.rx} {...common} />; // guard-ok
        return <Polyline key={i} points={el.pts} {...common} />; // guard-ok
      })}
    </Svg>
  );
}
