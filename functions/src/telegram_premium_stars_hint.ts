/** Официальный бот Telegram, где Stars покупаются отдельно от счёта. */
export const TELEGRAM_STARS_TOP_UP_BOT_URL = 'https://t.me/PremiumBot';

/** Текст подсказки: сколько Stars нужно и как пополнить баланс до оплаты. Чистая функция — сумма приходит из конфига цен. */
export function starsTopUpHintRu(stars: number): string {
  return [
    `Для оплаты нужно ${stars} Stars на балансе Telegram.`,
    '',
    'Если Telegram пишет «ошибка платёжной системы» — сначала пополните Stars отдельно, а потом вернитесь сюда и нажмите оплату ещё раз:',
    '1. Откройте @PremiumBot (кнопка ниже) и купите Stars там.',
    '2. Или в Telegram: Настройки → Мои звёзды → Пополнить.',
    '',
    'Счёт никуда не пропадёт. Не получается — напишите нам: /paysupport',
  ].join('\n');
}

/** Ряд с кнопкой-ссылкой на пополнение Stars (для inline_keyboard). */
export function starsTopUpKeyboardRow(): { text: string; url: string }[] {
  return [{ text: 'Пополнить Stars', url: TELEGRAM_STARS_TOP_UP_BOT_URL }];
}
