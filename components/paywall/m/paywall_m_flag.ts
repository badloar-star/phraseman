// зачем (координатор 25.10): владелец хочет М в большом обновлении, но включать его можно только после склейки «экран = макет» от Сверки. До этого флаг ВЫКЛ — окно
// остаётся прежним. Сбой чтения флага = выключено (старый экран безопаснее нового), причина пишется в журнал. Читает уже применённый снимок Remote Config: ни сети, ни хранилища.
// ═══════════════════════════════════════════════════════════════════════════
import { getRemoteBool } from '../../../app/remote_flags';

export function isPaywallMEnabled(): boolean {
  try {
    return getRemoteBool('paywall_m_enabled');
  } catch (error) {
    console.warn('[PAYWALL-M] чтение флага упало — показываю прежнее окно', error instanceof Error ? error.message : String(error)); // guard-ok: сбой пишет причину
    return false;
  }
}
