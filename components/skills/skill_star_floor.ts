/**
 * Минимальная длина луча звезды навыков (доля радиуса).
 *
 * зачем (обход экранов 12.11, визитка: «паутина при малых значениях — стрелка»): луч считается по макету (elevate-core.js, `axis`: корень из уровня),
 * и при нулях на всех осях, кроме одной-двух, фигура вырождается в клин. В макете нулевых профилей нет — минимального радиуса он не задаёт.
 * Умолчание: ноль рисуется маленьким ровным шестиугольником внутри первого кольца сетки (0,34), всё, что длиннее порога, — ровно по макету.
 * Числа и полоски рядом со звездой не меняются: это только вид фигуры.
 */
export const SKILL_STAR_MIN_AXIS = 0.12;

/** Длина луча для рисования: 0…1, не короче SKILL_STAR_MIN_AXIS. Мусор (NaN, ±∞) — как ноль. */
export function skillStarDisplayAxis(value: number): number {
  const safe = Number.isFinite(value) ? Math.max(0, Math.min(1, value)) : 0;
  return Math.max(SKILL_STAR_MIN_AXIS, safe);
}
