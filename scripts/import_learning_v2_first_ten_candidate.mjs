import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const APPROVED_SHA = '746b30c49c9735cd57cde89cb4e488c40e6661b1be9ccba1ac7f202b09957f09';
const root = process.cwd();
const sourceDir = path.join(root, 'modules', 'learning-v2', 'content', 'source');
const testsDir = path.join(root, 'tests');
const candidatePath = path.join(
  root,
  '.superpowers',
  'brainstorm',
  '871-1787210859',
  'content',
  'lesson1-first-ten-strict-gated-candidate-data-v2.js',
);
const projectionPath = path.join(sourceDir, 'approved_first_ten_candidate_v2.json');
const reportDir = path.join(root, '.codex-tmp', 'learning-v2-first-ten-import');
const reportPath = path.join(reportDir, 'report.json');
const apply = process.argv.includes('--apply');

const candidateRaw = fs.readFileSync(candidatePath, 'utf8');
const candidateSha = createHash('sha256').update(candidateRaw).digest('hex');
if (candidateSha !== APPROVED_SHA) throw new Error('approved_candidate_sha_mismatch');

const context = { window: {} };
vm.runInNewContext(candidateRaw, context);
const candidate = context.window.L1V2;
if (!candidate || candidate.version !== 2 || candidate.sessions?.length !== 10)
  throw new Error('approved_candidate_shape_invalid');

const projection = `${JSON.stringify(candidate)}\n`;
const wrapper = (ordinal) => {
  const nn = String(ordinal).padStart(2, '0');
  return `// Generated by scripts/import_learning_v2_first_ten_candidate.mjs.\n` +
    `// Learner-facing bytes come from the immutable owner-approved SHA below.\n` +
    `import { APPROVED_FIRST_TEN_SESSION_SOURCES_V2 } from './approved_first_ten_source_v2';\n\n` +
    `export const EPISODE_01_SESSION_${nn}_SOURCE =\n` +
    `  APPROVED_FIRST_TEN_SESSION_SOURCES_V2[${ordinal - 1}];\n`;
};
const phraseWrapper = (ordinal) => {
  const nn = String(ordinal).padStart(2, '0');
  return `// Generated by scripts/import_learning_v2_first_ten_candidate.mjs.\n` +
    `// This is the exact phrase slice used by the approved session source.\n` +
    `import { APPROVED_FIRST_TEN_PHRASE_SOURCES_V2 } from './approved_first_ten_source_v2';\n\n` +
    `export const EPISODE_01_SESSION_${nn}_PHRASES =\n` +
    `  APPROVED_FIRST_TEN_PHRASE_SOURCES_V2[${ordinal - 1}];\n`;
};
const testWrapper = (ordinal) => {
  const nn = String(ordinal).padStart(2, '0');
  return `// Generated by scripts/import_learning_v2_first_ten_candidate.mjs.\n` +
    `import { EPISODE_01_SESSION_${nn}_SOURCE } from '../modules/learning-v2/content/source/episode_01_session_${nn}_v1';\n` +
    `import { assertApprovedFirstTenSession } from './learning_v2_approved_first_ten_source_assertions';\n\n` +
    `describe('episode 1 approved session ${ordinal} source', () => {\n` +
    `  test('matches the exact approved projection and runtime contract', () => {\n` +
    `    assertApprovedFirstTenSession(EPISODE_01_SESSION_${nn}_SOURCE, ${ordinal});\n` +
    `  });\n` +
    `});\n`;
};

const writes = [
  [projectionPath, projection],
  ...Array.from({ length: 10 }, (_, index) => {
    const ordinal = index + 1;
    const nn = String(ordinal).padStart(2, '0');
    return [path.join(sourceDir, `episode_01_session_${nn}_v1.ts`), wrapper(ordinal)];
  }),
  ...Array.from({ length: 10 }, (_, index) => {
    const ordinal = index + 1;
    const nn = String(ordinal).padStart(2, '0');
    return [
      path.join(sourceDir, `episode_01_session_${nn}_phrases_v1.ts`),
      phraseWrapper(ordinal),
    ];
  }),
  ...Array.from({ length: 10 }, (_, index) => {
    const ordinal = index + 1;
    const nn = String(ordinal).padStart(2, '0');
    return [
      path.join(testsDir, `learning_v2_episode_01_session_${nn}_source.test.ts`),
      testWrapper(ordinal),
    ];
  }),
];

const changes = writes.filter(([file, body]) =>
  !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== body,
);
if (apply) {
  for (const [file, body] of changes) fs.writeFileSync(file, body, 'utf8');
}

fs.mkdirSync(reportDir, { recursive: true });
fs.writeFileSync(
  reportPath,
  `${JSON.stringify(
    {
      schemaVersion: 'learning-v2-first-ten-import-report.v1',
      mode: apply ? 'apply' : 'dry-run',
      approvedCandidateSha256: candidateSha,
      productionProjectionSha256: createHash('sha256').update(projection).digest('hex'),
      sessions: candidate.sessions.length,
      locales: candidate.localeOrder.length,
      changedPaths: changes.map(([file]) => path.relative(root, file).replaceAll('\\', '/')),
    },
    null,
    2,
  )}\n`,
  'utf8',
);

console.log(
  `${apply ? 'APPLIED' : 'DRY RUN'}: ${candidate.sessions.length} sessions, ` +
    `${candidate.localeOrder.length} locales, ${changes.length} changed paths.`,
);
console.log(`REPORT: ${path.relative(root, reportPath)}`);
