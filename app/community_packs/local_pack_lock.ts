// local_pack_lock.ts — очередь по id локального набора вокруг цикла «прочитать набор → изменить карточки → записать».
//
// зачем (аудит Optimistic UI 15.10, решение координатора): удалить/вернуть/добавить карточку = чтение набора ВНЕ очереди записи + запись целиком.
// Две быстрые правки одного набора читали одно и то же состояние, и вторая запись затирала первую: удалённая карточка «воскресала»,
// добавленная пропадала — потеря правки пользователя без единого сообщения. Теперь вторая правка ждёт первую и читает уже записанное.
// Очередь отдельная от общей очереди записи `localAuthorPacks` (та охраняет сам момент записи); вложение идёт в одну сторону, взаимной блокировки нет.
import { createSerialPerKey } from './serial_per_key';

const serial = createSerialPerKey();

/** Выполнить правку набора строго по очереди с другими правками ЭТОГО набора; разные наборы идут параллельно. */
export function withLocalPackLock<T>(packId: string, task: () => Promise<T>): Promise<T> {
  return serial(`local_pack:${packId}`, task);
}
