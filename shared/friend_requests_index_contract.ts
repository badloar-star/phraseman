/**
 * Контракт обратного индекса исходящих заявок в друзья.
 *
 * зачем: удаление аккаунта обязано снести заявки, которые игрок отправил другим
 * людям. Заявка живёт по адресу `users/{toUid}/friend_requests/{fromUid}` — uid
 * отправителя лежит в ИМЕНИ документа, а не в поле, поэтому collection-group
 * запросом её не найти (Firestore сравнивает documentId по полному пути).
 * Раньше единственным способом был перебор всей коллекции `users` на каждое
 * удаление: при 100k игроков это сотни тысяч чтений и таймаут функции.
 *
 * Решение: отправитель дублирует у себя лёгкую отметку
 * `users/{fromUid}/friend_requests_sent/{toUid}`. Она содержит только адресата
 * и время, никакого PII, и позволяет удалению пройти по десяткам документов
 * вместо всей базы.
 *
 * Оба конца (app/firestore_friend_requests.ts и functions/src/account_delete.ts)
 * читают имена ОТСЮДА — правишь здесь, ничего больше править не нужно.
 */

/** Подколлекция под документом отправителя. */
export const FRIEND_REQUESTS_SENT_INDEX = 'friend_requests_sent';

/**
 * Служебный документ-маркер «этот аккаунт ведёт индекс».
 *
 * Пустая подколлекция неотличима от отсутствующей: и там и там ноль документов.
 * Без маркера удаление не смогло бы понять, можно ли доверять узкому пути, и
 * навсегда осталось бы на аварийном полном переборе.
 *
 * зачем именно такое имя (ИНЦИДЕНТ 2026-08-29): раньше здесь стояло
 * `__index__`, и весь механизм был мёртв с рождения — Firestore РЕЗЕРВИРУЕТ
 * любой id вида `__…__` и отвечает `INVALID_ARGUMENT: Resource id is invalid
 * because it is reserved`. Маркер поэтому не мог быть ни записан, ни прочитан,
 * а бросок из `.doc()` валил стадию `collect_peers` и через неё ВСЁ удаление
 * аккаунта: пять боевых задач умерли с `account_delete_failed`, данные людей,
 * запросивших удаление, остались в базе.
 *
 * Новое имя обязано быть (а) валидным id — без обрамляющих `__`, (б)
 * невозможным как настоящий uid. Firebase-uid — 28 символов [A-Za-z0-9],
 * stable-id — UUID v4; обе формы не содержат точки, поэтому `.` в имени
 * гарантирует отсутствие коллизии навсегда.
 *
 * Сторож `tests/firestore_reserved_document_id_guard.test.ts` не даст вернуть
 * зарезервированную форму.
 */
export const FRIEND_REQUESTS_SENT_MARKER_ID = 'marker.index';

/** Тело отметки об исходящей заявке. */
export interface FriendRequestSentEntry {
  /** Кому отправлена заявка (дублирует id документа — удобно для отладки). */
  toUid: string;
  createdAt: number;
}
