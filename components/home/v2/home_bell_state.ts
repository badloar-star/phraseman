import { createContext } from 'react';

/**
 * Состояние Главной для колокольчика: «вкладка активна» и счётчик фокусов.
 *
 * зачем (координатор 18.10, [HOME-CHILD-COST]: шапка 8–14 мс на каждом возврате «назад»): колокольчик получал `isHomeTabActive` и `homeFocusTick` ПРОПСАМИ внутри элемента `bellSlot` —
 * оба меняются на каждом возврате, из-за чего элемент `bellSlot` отличался и шапка (memo со сравнением элементов) перерисовывалась целиком вместе со всеми показателями. Теперь Главная кладёт эти два
 * значения в контекст вокруг шапки, колокольчик читает их оттуда сам, а элемент `bellSlot` не меняется: на возврате обновляется только колокольчик, шапка пропускается. Без провайдера
 * (другое место использования) колокольчик берёт прежние пропсы — поведение то же.
 */
export type HomeBellState = Readonly<{ active: boolean; focusTick: number }>;

export const HomeBellStateContext = createContext<HomeBellState | null>(null);
