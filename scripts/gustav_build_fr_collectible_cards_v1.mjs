function buildFinalGate(catalog, audit, sourceManifest, dalleQueue, adminHandoff) {
  const allRows = flatten(catalog);
  const sourceRowsReady = sourceManifest.summary.rowsWithAtLeastTwoTrustedSources === allRows.length;
  const queueReady = dalleQueue.length === allRows.length;
  const generatedWebpAssetPaths = dalleQueue
    .map((item) => item.targetPath)
    .filter((targetPath) => fs.existsSync(path.join(ROOT, targetPath)));
  return {
    schemaVersion: 'gustav-fr-collectible-final-gate-v1',
    generatedAt: GENERATED_AT,
    status: 'HOLD_CANDIDATE_READY_ASSETS_AND_LIVE_SOURCE_CHECK_OPEN',
    productionReady: false,
    studyTarget: 'fr',
    summary: {
      sets: catalog.sets.length,
      rows: allRows.length,
      regularCards: allRows.filter((row) => row.kind === 'card').length,
      secretCards: allRows.filter((row) => row.kind === 'secret').length,
      rarity: countFrench(catalog).rarity,
      sourceRowsReady,
      liveSourceFetchedRows: 0,
      dalleQueueItems: dalleQueue.length,
      dalleQueueReady: queueReady,
      generatedWebpAssets: generatedWebpAssetPaths.length,
      activationApproved: false,
    },
    passGates: [
      'english_blueprint_shape_parity',
      'french_native_candidate_count',
      'rarity_distribution_parity',
      'dalle_queue_manifest_ready',
      'admin_handoff_ready',
    ],
    holdGates: [
      'live_source_verification_all_330',
      'dalle_generation_all_330',
      'image_upload_url_map',
      'runtime_server_target_isolation_apply',
      'explicit_activation_approval',
    ],
    artifacts: {
      auditHash: sha256(JSON.stringify(audit)),
      catalogHash: sha256(JSON.stringify(catalog)),
      sourceManifestHash: sha256(JSON.stringify(sourceManifest)),
      dalleQueueHash: sha256(dalleQueue.map((item) => JSON.stringify(item)).join('\n')),
      adminHandoffHash: sha256(JSON.stringify(adminHandoff)),
    },
    generatedWebpAssetPaths,
    safety: SAFETY,
  };
}

function writeMarkdownSummary(filePath, finalGate, catalog) {
  const lines = [
    '# Gustav French Collectible Cards V1',
    '',
    `Generated: ${GENERATED_AT}`,
    '',
    `Status: \`${finalGate.status}\``,
    '',
    `Sets: ${catalog.sets.length}`,
    `Rows: ${finalGate.summary.rows}`,
    `Rarity: common ${finalGate.summary.rarity.common}, rare ${finalGate.summary.rarity.rare}, epic ${finalGate.summary.rarity.epic}, legendary ${finalGate.summary.rarity.legendary}`,
    '',
    '## Hold Gates',
    '',
    ...finalGate.holdGates.map((gate) => `- \`${gate}\``),
    '',
    '## Sample Rows',
    '',
    ...flatten(catalog).slice(0, 12).map((row) => `- \`${row.id}\` ${row.fr} — ${row.ru}`),
    '',
  ];
  fs.writeFileSync(filePath, `${lines.join('\n')}\n`, 'utf8');
}

function main() {
  const englishSeed = readEnglishSeed();
  const catalog = buildFrenchCatalog(englishSeed);
  const audit = buildEnglishBlueprintAudit(englishSeed, catalog);
  const sourceManifest = buildSourceEvidence(catalog);
  const dalleQueue = buildDalleQueue(catalog);
  const adminHandoff = buildAdminHandoff(catalog, audit, sourceManifest, dalleQueue);
  const finalGate = buildFinalGate(catalog, audit, sourceManifest, dalleQueue, adminHandoff);

  fs.mkdirSync(OUT_DIR, { recursive: true });
  writeJson(path.join(OUT_DIR, 'fr_collectible_catalog_v1.json'), catalog);
  writeJson(path.join(OUT_DIR, 'fr_collectible_english_blueprint_audit_v1.json'), audit);
  writeJson(path.join(OUT_DIR, 'fr_collectible_source_evidence_manifest_v1.json'), sourceManifest);
  writeJsonl(path.join(OUT_DIR, 'fr_collectible_dalle_queue_v1.jsonl'), dalleQueue);
  writeJson(path.join(OUT_DIR, 'fr_collectible_admin_handoff_v1.json'), adminHandoff);
  writeJson(path.join(OUT_DIR, 'fr_collectible_final_gate_v1.json'), finalGate);
  writeMarkdownSummary(path.join(OUT_DIR, 'fr_collectible_cards_v1.md'), finalGate, catalog);

  console.log(JSON.stringify({
    status: finalGate.status,
    sets: catalog.sets.length,
    rows: finalGate.summary.rows,
    rarity: finalGate.summary.rarity,
    dalleQueueItems: dalleQueue.length,
    activationApproved: false,
    outputDir: rel(OUT_DIR),
  }, null, 2));
}

main();
