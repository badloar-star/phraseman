// tournament_prize_forecast.ts — прогноз призов для ЛОББИ.
//
// зачем 2026-08-03 (владелец: «места пусть вместо процентов сразу показывают
// точные цифры жемчугов, тоже анимированно, округлять но точно»): в лобби доли
// призёров были ЗАХАРДКОЖЕНЫ как «60% / 25% / 15%». Процент — это не награда:
// игрок не знает банк наизусть и не считает проценты в уме, пока идёт отсчёт.
// Теперь показываем жемчужины.
//
// Почему отдельный модуль, а не пара строк в экране: цифра в лобби — ОБЕЩАНИЕ
// выплаты. Если она разойдётся с тем, что сервер реально заплатит в конце,
// это хуже процентов — это обман. Формула обязана повторять серверную
// (functions/src/tournament_economy.ts) один в один и быть покрыта тестами.
//
// Модуль ЧИСТЫЙ: только арифметика, ни сети, ни React.
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Доля банка, уходящая в недельный банк.
 *
 * зачем: сервер (tournament_economy.ts → weeklyBankRate) снимает эту долю ДО
 * раздачи призёрам. Показывать доли от полного банка означало бы обещать
 * больше, чем игрок получит: при банке 80 «60%» это 48, а на руки придёт 38.
 * Тот же множитель 0.8 уже используется на экране результатов как фолбэк —
 * держим одну формулу на оба экрана.
 */
const WEEKLY_BANK_RATE = 0.2;

/** Доли призёров 1-2-3 места. Совпадают с prizeShares серверной экономики. */
const PRIZE_SHARES = [0.6, 0.25, 0.15] as const;

/**
 * Сколько из банка реально достанется призёрам.
 *
 * Округление вниз — как на сервере (`Math.floor(total * weeklyBankRate)`),
 * остаток от округления остаётся в призах игрокам, а не исчезает.
 */
// guard-ok: это ПРОГНОЗ ДЛЯ ПОКАЗА, а не изменение баланса. Функция ничего не
// записывает — ни в Firestore, ни в локальное состояние кошелька; она считает
// подпись под плашкой места. Балансы меняет только сервер
// (functions/src/tournament_economy.ts), клиент источником истины не является.
export function tournamentPrizePoolForecast(potGems: number): number {
  // зачем: Infinity и NaN обязаны гаситься ДО арифметики — иначе в подпись
  // места уйдёт «NaN», и игрок увидит сломанный экран вместо награды.
  // `Number.isFinite` ловит оба случая, `|| 0` — не ловит Infinity.
  const raw = Number(potGems);
  if (!Number.isFinite(raw)) return 0;
  const pot = Math.max(0, Math.trunc(raw));
  if (pot === 0) return 0;
  return pot - Math.floor(pot * WEEKLY_BANK_RATE);
}

/**
 * Прогноз выплат по местам [1-е, 2-е, 3-е].
 *
 * зачем (решение владельца 2026-08-03): округляем ВНИЗ по каждому месту.
 * Сервер отдаёт остаток от округления первому месту (splitByShares), поэтому
 * победитель по факту может получить на 1-2 жемчужины БОЛЬШЕ обещанного —
 * приятный сюрприз. Обратного (получить меньше показанного) не бывает ни на
 * одном месте, а это и есть главное требование к обещанию.
 */
export function tournamentPrizeForecast(potGems: number): readonly [number, number, number] {
  const prizePool = tournamentPrizePoolForecast(potGems);
  if (prizePool === 0) return [0, 0, 0];
  return [
    Math.floor(prizePool * PRIZE_SHARES[0]),
    Math.floor(prizePool * PRIZE_SHARES[1]),
    Math.floor(prizePool * PRIZE_SHARES[2]),
  ];
}
