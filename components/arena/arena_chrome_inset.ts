import { createContext, useContext } from 'react';

/**
 * Сколько места снизу занимает обвязка Арены (плавающий таббар).
 *
 * Раньше это место вычиталось у обвязки: контейнер с содержимым получал
 * `paddingBottom`, и экран вместе со своим фоном заканчивался НАД таббаром.
 * Таббар — плавающая пилюля с полями по 14 pt и тенью, поэтому вокруг него
 * оставалась полоса чужого цвета: ровная заливка вместо арта Арены. Владелец
 * увидел это как «чёрную полосу снизу» и потребовал «как на главной», где фон
 * идёт до самого края.
 *
 * Теперь экран занимает всю высоту вместе с фоном, а место под таббар
 * добавляется к отступу СОДЕРЖИМОГО — его и передаёт этот контекст. Экраны
 * Арены вне обвязки получают ноль и ведут себя как прежде.
 */
export const ArenaChromeInsetContext = createContext(0);

export function useArenaChromeInset(): number {
  return useContext(ArenaChromeInsetContext);
}
