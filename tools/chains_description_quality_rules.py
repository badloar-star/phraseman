def build_strict_russian_explanation(chain: dict[str, Any]) -> str:
    idx = int(chain["index"])
    if idx in STRICT_EXPLANATIONS:
        text = clean_text(STRICT_EXPLANATIONS[idx])
        first = words(text)[:1]
        if first and len(first[0]) <= 1:
            text = "Здесь " + text[:1].lower() + text[1:]
        return clean_text(text)
    category = infer_category(chain)
    opener = OPENERS[(idx - 1) % len(OPENERS)]
    body = category_body(category, idx - 1, str(chain.get("half", "")))
    return clean_text(f"{opener} {body}")


