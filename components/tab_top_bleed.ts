// ═══════════════════════════════════════════════════════════════════════════
// tab_top_bleed.ts — высота зоны часов для «полноэкранной» вкладки.
//
// зачем (владелец 22.10: «ВЕРХНЯЯ СЕЙФ-ЗОНА ВСЕГДА ЧАСТЬ ОБЩЕЙ КОМПОЗИЦИИ… КАКАЯ БЫ ТЕМА НИ БЫЛА, ОНА НЕ ОТЛИЧАЕТСЯ ПО ЦВЕТУ»):
// оболочка вкладок отступает на insets.top у каждой страницы, кроме полноэкранных. Полноэкранная вкладка рисует свой фон от самого
// верха экрана, а шапку и содержимое отодвигает на это значение. 0 — страница уже под отступом оболочки (или вне вкладок).
// ═══════════════════════════════════════════════════════════════════════════
import { createContext, useContext } from 'react';

export const TabTopBleedContext = createContext<number>(0);

export function useTabTopBleedInset(): number {
  return useContext(TabTopBleedContext);
}

// зачем (закон владельца 22.10: «кнопка назад везде в одном месте»): 0 выше значит и «страница под отступом оболочки», и «экран вне
// вкладок» — абсолютному слою (ScreenBackButton) их нужно различать: экран стека начинается от верха экрана, страница вкладки — нет.
export const TabPageContext = createContext<boolean>(false);

export function useIsTabPage(): boolean {
  return useContext(TabPageContext);
}
