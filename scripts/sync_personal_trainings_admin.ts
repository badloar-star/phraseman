import fs from 'node:fs';
import path from 'node:path';

import { getAllDiagnosisTrainings } from '../app/diagnosis_trainings';
import {
  getPersonalTrainingTaxonomyEntry,
  JESSE_REWORKED_MARKER,
  PERSONAL_TRAINING_TAXONOMY,
} from '../app/personal_training_taxonomy';

const root = process.cwd();
const outputPath = path.join(root, 'admin', 'personal-trainings.js');

const trainings = getAllDiagnosisTrainings()
  .map((training) => {
    const taxonomy = getPersonalTrainingTaxonomyEntry(training.id);
    const jesseStatus = taxonomy?.jesseStatus ?? 'legacy_needs_rework';
    return {
      id: training.id,
      category: training.category,
      status: taxonomy?.status ?? 'legacy_needs_rework',
      jesseStatus,
      needsJesseRework: jesseStatus !== 'reworked',
      jesseMarker: taxonomy?.jesseMarker ?? null,
      qaStatus: taxonomy?.qaStatus ?? 'PENDING',
      appPath: taxonomy?.appPath ?? `app/diagnosis_training_${training.id}.ts`,
      sourceDraft: taxonomy?.sourceDraft ?? null,
      qaReport: taxonomy?.qaReport ?? null,
      title: training.title,
      shortDiagnosis: training.shortDiagnosis,
      stepCount: training.steps.length,
      contrastSet: training.contrastSet,
      registryPath: 'app/diagnosis_trainings.ts',
    };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

const activeIds = PERSONAL_TRAINING_TAXONOMY
  .filter((item) => item.status === 'active')
  .map((item) => item.id)
  .sort();

const jesseReworkedIds = trainings
  .filter((item) => item.jesseStatus === 'reworked')
  .map((item) => item.id)
  .sort();

const legacyNeedsReworkIds = trainings
  .filter((item) => item.needsJesseRework)
  .map((item) => item.id)
  .sort();

const payload = {
  generatedAt: new Date().toISOString(),
  source: 'scripts/sync_personal_trainings_admin.ts',
  registryPath: 'app/diagnosis_trainings.ts',
  taxonomyPath: 'app/personal_training_taxonomy.ts',
  jesseReworkedMarker: JESSE_REWORKED_MARKER,
  activeIds,
  jesseReworkedIds,
  legacyNeedsReworkIds,
  trainings,
};

const body = [
  '/* eslint-disable */',
  '// Generated by npm run training:personal:sync-admin.',
  '// Do not edit manually. Update app diagnosis trainings and taxonomy, then rerun the sync.',
  `window.PERSONAL_TRAININGS_MANIFEST = ${JSON.stringify(payload, null, 2)};`,
  '',
].join('\n');

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, body, 'utf8');

console.log(
  `Synced ${trainings.length} personal trainings to ${path.relative(root, outputPath)} `
  + `(${jesseReworkedIds.length} Jesse reworked, ${legacyNeedsReworkIds.length} legacy need rework)`,
);
