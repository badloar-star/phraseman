import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const file = path.join(root, "sessions", "en", "l02", "s06", "practice.atomic.json");
const substitutions = new Map([
  ["женщина с телефоном-картой", "Ира с телефоном-картой"],
  ["жінка з телефоном-мапою", "Іра з телефоном-мапою"],
  ["женщина уронила сумку", "Ольга уронила сумку"],
  ["жінка впустила сумку", "Ольга впустила сумку"],
  ["мальчик без куртки", "Никита без куртки"],
  ["хлопчик без куртки", "Микита без куртки"],
  ["спросить, не хочет ли человек пить", "спросить Иру, не хочет ли она пить"],
  ["запитати, чи не хоче людина пити", "запитати Іру, чи не хоче вона пити"],
  ["человек третий раз проходит", "Никита третий раз проходит"],
  ["людина втретє проходить", "Микита втретє проходить"],
  ["спросите, не заблудился ли он", "спросите Никиту, не заблудился ли он"],
  ["запитайте, чи вона не заблукала", "запитайте Микиту, чи він не заблукав"],
  ["человек стоит у фонтанчика", "Ира стоит у фонтанчика"],
  ["людина стоїть біля фонтанчика", "Іра стоїть біля фонтанчика"],
]);

const source = fs.readFileSync(file, "utf8");
const updated = [...substitutions].reduce((text, [from, to]) => text.split(from).join(to), source);
if (updated === source) throw new Error("l02/s06 actor repair made no change");
JSON.parse(updated);
fs.writeFileSync(file, updated, "utf8");
