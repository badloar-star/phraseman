function retryFor(correct: string, clue: TriText, finalHint: TriText): [TriText, TriText, TriText, TriText] {
  return [
    tri(
      'Сначала поймай тип сравнения: больше/дешевле/лучше, длинное слово с more, или равное сравнение as ... as.',
      'Спочатку впіймай тип порівняння: більше/дешевше/краще, довге слово з more, або рівне порівняння as ... as.',
      'First choose the comparison pattern.',
    ),
    clue,
    tri(
      'Потом проверь хвост. Если есть прямое сравнение, часто нужен than: cheaper than, more expensive than, better than.',
      'Потім перевір хвіст. Якщо є пряме порівняння, часто потрібен than: cheaper than, more expensive than, better than.',
      'Then check than: cheaper than, more expensive than, better than.',
    ),
    tri(
      'Здесь выбери вариант, где сравнение собрано без двойного усиления и с правильным хвостом.',
      'Тут обери варiант, де порiвняння зiбране без подвiйного пiдсилення i з правильним хвостом.',
      `The answer here is ${correct}. ${finalHint.es}`,
    ),
  ];
}

function defaultWrong(correct: string): TriText {
  return tri(
    `Почти. Форма сравнения не собралась. Здесь нужен вариант: ${correct}.`,
    `Майже. Форма порівняння не зібралася. Тут потрібен варіант: ${correct}.`,
    `Almost. Use: ${correct}.`,
  );
}

function comparisonStep(input: {
  id: string;
  order: number;
  difficulty: DiagnosisTrainingStep['difficulty'];
  targetSkill: string;
  sentence: string;
  translation: TriText;
  options: string[];
  correctAnswer: string;
  correctFeedback: TriText;
  wrong: Record<string, TriText>;
  clue: TriText;
  finalHint: TriText;
  focusWords: string[];
}): DiagnosisTrainingStep {
  return {
    id: input.id,
    order: input.order,
    difficulty: input.difficulty,
    type: 'single_choice',
    targetSkill: input.targetSkill,
    translation: input.translation,
    teachingText: MODEL,
    explanationBlock: MODEL,
    microTask: tri(
      'Выбери нормальный кусок сравнения.',
      'Обери нормальний шматок порівняння.',
      'Choose the comparison chunk.',
    ),
    sentence: input.sentence,
    answerOptions: input.options.map((text) => ({ id: text, text })),
    correctAnswerId: input.correctAnswer,
    correctIndex: input.options.findIndex((option) => option === input.correctAnswer),
    correctFeedback: input.correctFeedback,
    wrongFeedbackByOption: Object.fromEntries(
      input.options
        .filter((option) => option !== input.correctAnswer)
        .map((option) => [option, input.wrong[option] ?? defaultWrong(input.correctAnswer)]),
    ),
    retryFeedback: retryFor(input.correctAnswer, input.clue, input.finalHint),
    fallbackExplanation: tri(
      'Коротко: cheap -> cheaper, big -> bigger, easy -> easier. Длинные слова часто: more expensive, more useful. Good -> better, bad -> worse. Равное сравнение: as good as.',
      'Коротко: cheap -> cheaper, big -> bigger, easy -> easier. Довгі слова часто: more expensive, more useful. Good -> better, bad -> worse. Рівне порівняння: as good as.',
      'Short version: cheaper, bigger, easier, more expensive, better, worse, as good as.',
    ),
    focusWords: input.focusWords,
  };
}

