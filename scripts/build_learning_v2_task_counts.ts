// build_learning_v2_task_counts.ts — число заданий каждого занятия курса для лёгкого индекса (окно эпизода в «Обучении»).
// зачем (3 · МАКЕТЫ, Сверка 24.10: окно эпизода писало «0 заданий», в занятии их 19): Сезон берёт числа только из лёгкого
// индекса — тяжёлый JSON занятия на карусели грузить нельзя. Считаем ТЕМ ЖЕ сборщиком, что плеер (карточки слов не задания),
// и пишем рядом отпечаток содержимого: разошёлся с каталогом — приложение число не покажет (лучше ничего, чем неверное).
// Запуск: npx tsx scripts/build_learning_v2_task_counts.ts  (тяжёлый — через светофор).
import fs from "node:fs";
import path from "node:path";

import { FACTORY_NATIVE_MANIFEST_V1 } from "../modules/learning-v2/content/factory_native/factory_native_manifest_v1.generated";
import { materializeFactoryNativeLearningV2SessionV1 } from "../modules/learning-v2/content/factory_native/factory_native_course_v1";

const OUT = path.join(__dirname, "..", "modules", "learning-v2", "content", "factory_native", "factory_native_task_counts_v1.generated.ts");
const LOG = "[TASK-COUNTS]";

const rows: string[] = [];
let failed = 0;
const quiet = console.log;
for (const row of FACTORY_NATIVE_MANIFEST_V1) {
  const key = `${row.lessonOrdinal}:${row.sessionOrdinal}`;
  try {
    console.log = () => undefined; // сборщик пишет строку на каждое занятие — здесь это шум
    const built = materializeFactoryNativeLearningV2SessionV1({ lessonOrdinal: row.lessonOrdinal, sessionOrdinal: row.sessionOrdinal, interfaceLocale: "ru" });
    console.log = quiet;
    if (!built) { failed += 1; console.warn(LOG, "not_materialized", key); continue; }
    // зачем: 16 знаков отпечатка хватает, чтобы заметить смену содержимого, а файл легче втрое (он в бандле)
    rows.push(`  "${key}": [${built.learnerChild.interactions.length}, ${JSON.stringify(row.sourceFingerprint.slice(0, 16))}],`);
  } catch (error) {
    console.log = quiet;
    failed += 1;
    console.warn(LOG, "failed", key, error instanceof Error ? error.message : String(error));
  }
}
const body = `/* This file is generated by scripts/build_learning_v2_task_counts.ts. Do not edit by hand. */\n` +
  `/* «урок:занятие» → [число заданий практики (без карточек слов), первые 16 знаков отпечатка содержимого занятия]. */\n` +
  `export const FACTORY_NATIVE_TASK_COUNTS_V1: Readonly<Record<string, readonly [number, string]>> = Object.freeze({\n${rows.join("\n")}\n});\n`;
fs.writeFileSync(OUT, body);
console.log(LOG, "done", JSON.stringify({ sessions: rows.length, failed, out: path.relative(process.cwd(), OUT) }));
