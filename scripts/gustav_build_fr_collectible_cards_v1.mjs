function countEnglish(seed) {
  const rarity = { common: 0, rare: 0, epic: 0, legendary: 0 };
  for (const setItem of seed.sets) for (const card of setItem.cards) rarity[card.rarity] += 1;
  return {
    sets: seed.sets.length,
    cards: seed.sets.reduce((sum, setItem) => sum + setItem.cards.length, 0),
    secrets: seed.sets.length,
    rarity,
    setTypes: seed.sets.reduce((acc, setItem) => {
      acc[setItem.type] = (acc[setItem.type] || 0) + 1;
      return acc;
    }, {}),
  };
}

