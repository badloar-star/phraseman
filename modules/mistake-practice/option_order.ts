/**
 * Порядок вариантов ответа в «Моих ошибках».
 *
 * зачем (F05, 11.11: «последний вариант правильный»): варианты собирались как
 * [отвлекающие..., верный] и показывались как есть — верный всегда стоял
 * последним, задание решалось не глядя. Перемешиваем устойчиво от зерна:
 * внутри одной сессии порядок не прыгает при перерисовке, а между сессиями
 * меняется (зерно включает соль сессии), чтобы место верного не заучивалось.
 *
 * Чистая функция: вход не мутируется, Math.random не используется.
 */
export function mistakePracticeOptionOrder<T>(options: readonly T[], seedText: string): T[] {
  const out = [...options];
  if (out.length < 2) return out;
  // FNV-1a по тексту зерна → стартовое число генератора.
  let seed = 2166136261;
  for (let i = 0; i < seedText.length; i += 1) {
    seed = Math.imul(seed ^ seedText.charCodeAt(i), 16777619) >>> 0;
  }
  // Финальное размешивание бит: без него близкие зёрна («…:1», «…:2»)
  // дают близкие числа и перекос мест у коротких списков.
  const next = (): number => {
    seed = (seed + 0x6d2b79f5) >>> 0;
    let t = seed;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 0x100000000;
  };
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(next() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
