/**
 * Общий потолок системного размера шрифта для всего текста приложения.
 *
 * зачем (владелец 11.11.2026, жалоба пользователя Стеллы): на телефоне с крупным системным шрифтом и увеличенным масштабом экрана
 * текст рос без предела — вопрос упражнения не помещался в карточку, поле ввода уходило под клавиатуру. Свой потолок стоял только
 * примерно у 12% текстов; остальные росли вплоть до ×2. Владелец: «интерфейс обязан подстраиваться под размер устройства».
 *
 * Как применяется: патч `patches/react-native+0.81.5.patch` ставит это число значением `maxFontSizeMultiplier` по умолчанию в Text и
 * TextInput (defaultProps на React 19 не работают, поэтому — там же, где уже прибит шрифт Inter). Явный `maxFontSizeMultiplier` на
 * конкретном тексте по-прежнему побеждает (и меньший, и больший). Число в патче и здесь обязано совпадать — сторож
 * `tests/font_scale_cap_contract.test.ts`.
 *
 * Почему 1.3: в проекте уже использовались 1.15–1.35; 1.3 оставляет заметное увеличение для слабого зрения и не ломает вёрстку.
 */
export const APP_MAX_FONT_SCALE = 1.3;

/** Системный масштаб шрифта, каким его реально увидит текст без своего потолка: не меньше 1 и не больше общего потолка. */
export function effectiveFontScale(fontScale: number, maxMultiplier: number = APP_MAX_FONT_SCALE): number {
  if (!Number.isFinite(fontScale) || fontScale <= 1) return 1;
  return Math.min(fontScale, maxMultiplier);
}
