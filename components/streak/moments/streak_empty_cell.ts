// streak_empty_cell.ts — цвет ПУСТОЙ клетки календаря рубежа: нейтральный «белый/чёрный 8 %» поверх фона экрана.
// зачем (координатор 18.10, Макеты d30 по эталону engagement-moments-v3-all.html: пустые клетки — белый 7 % поверх фона ≈#1D1E20; расчёт Темы по 23 темам × насыщенность 0/0,5/1):
//  • прежняя заливка opaqueControl: в светлых темах совпадала с фоном (1,00:1 — клетка не видна), в тёмных 1,09:1, к тому же с оттенком акцента (зеленоватая в «Авроре»);
//  • белый 7 % даёт в тёмных худшее 1,13 (27 из 69 сочетаний ниже 1,15); 8 % — худшее 1,15 в тёмных и 1,19 в светлых, ни одного сочетания ниже 1,15; к заполненной клетке — не ниже 6,6:1 (тёмные) и 4,7:1 (светлые);
//  • в светлых темах тон — чёрный 8 % (белый на светлом фоне не виден). Различие с эталоном 1 % на глаз не заметно.
// Цвет — rgba, поэтому он лежит прямо на градиенте фона (bg → bgTop) и «белый/чёрный α поверх фона» верен в любой точке.
const CELL_ALPHA = 0.08;
// зачем (Макеты 18.10, d30 светлая light_t8: «пустые клетки почти не видны»): на светлом фоне 8 % давали ~1,19:1 — чёрный 14 %.
const CELL_ALPHA_LIGHT = 0.14;

const luminance = (hex: string): number => {
  const m = /^#([0-9a-fA-F]{6})/u.exec(hex);
  if (!m) return 0;
  const n = parseInt(m[1]!, 16);
  const c = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => v / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0]! + 0.7152 * c[1]! + 0.0722 * c[2]!;
};

/** Пустая клетка: белый 8 % на тёмном фоне, чёрный 14 % на светлом (граница — яркость фона 0,4). */
export function streakEmptyCellColor(bg: string): string {
  return luminance(bg) > 0.4 ? `rgba(0,0,0,${CELL_ALPHA_LIGHT})` : `rgba(255,255,255,${CELL_ALPHA})`; // theme-exempt: нейтральная заливка поверх фона темы, считается от bg (белый/чёрный 8 %, эталон d30)
}
