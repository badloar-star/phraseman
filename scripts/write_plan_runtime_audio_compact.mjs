#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(SCRIPT_PATH), '..');
const AUTHORING_MANIFEST_PATH = path.join(
  ROOT,
  'app',
  'personal_plan_runtime_audio_assets.generated.ts',
);
const COMPACT_MANIFEST_PATH = path.join(
  ROOT,
  'app',
  'personal_plan_runtime_audio_assets.compact.generated.ts',
);
const CONTENT_UNIT_PATTERN = /^([a-z0-9]+)_d(\d{3})_content_unit_phrase_(\d+)$/;

function readAuthoringAssets() {
  const source = fs.readFileSync(AUTHORING_MANIFEST_PATH, 'utf8');
  const assignment = source.indexOf('= [');
  const arrayEnd = source.lastIndexOf(']');
  if (assignment === -1 || arrayEnd === -1) {
    throw new Error('Runtime audio authoring manifest does not contain a JSON array assignment.');
  }
  return JSON.parse(source.slice(assignment + 2, arrayEnd + 1));
}

function expectedDerivedFields(plan, day, phraseNumber) {
  const dayPadded = String(day).padStart(3, '0');
  const dayId = `${plan}_d${dayPadded}`;
  const daySlug = `${plan}-d${dayPadded}`;
  const phraseSlug = `${daySlug}-content-unit-phrase-${phraseNumber}`;
  const assetId = `audio:${plan}:runtime:${daySlug}-listen-audio:${phraseSlug}`;
  return {
    assetId,
    blockId: `${dayId}:listen-audio`,
    uri: `assets/audio/personal-plans-runtime/${plan}/runtime/${daySlug}-listen-audio/${phraseSlug}.mp3`,
  };
}

function buildCompactGroups(assets) {
  const groups = new Map();

  for (const asset of assets) {
    if (!Array.isArray(asset.contentUnitIds) || asset.contentUnitIds.length !== 1) {
      throw new Error(`Runtime audio asset ${asset.id ?? '<unknown>'} must map to exactly one content unit.`);
    }
    const contentUnitId = asset.contentUnitIds[0];
    const match = CONTENT_UNIT_PATTERN.exec(contentUnitId);
    if (!match) {
      throw new Error(`Unsupported runtime audio content unit id: ${contentUnitId}`);
    }

    const [, plan, dayPadded, phraseRaw] = match;
    const day = Number(dayPadded);
    const phraseNumber = Number(phraseRaw);
    const expected = expectedDerivedFields(plan, day, phraseNumber);
    const invariantMatches =
      asset.id === expected.assetId &&
      asset.assetId === expected.assetId &&
      asset.blockId === expected.blockId &&
      asset.uri === expected.uri &&
      asset.locale === 'en' &&
      asset.status === 'approved' &&
      asset.voiceId === 'openai:alloy' &&
      asset.provider === 'openai' &&
      asset.finalAssetReady === true &&
      typeof asset.targetText === 'string' &&
      asset.targetText.trim().length > 0 &&
      Number.isFinite(asset.durationMs) &&
      asset.durationMs > 0;
    if (!invariantMatches) {
      throw new Error(`Runtime audio asset ${contentUnitId} no longer matches compact-index invariants.`);
    }

    const groupKey = `${plan}:${dayPadded}`;
    let group = groups.get(groupKey);
    if (!group) {
      group = { plan, day, phrases: [] };
      groups.set(groupKey, group);
    }
    if (group.phrases[phraseNumber - 1]) {
      throw new Error(`Duplicate runtime audio phrase ${contentUnitId}.`);
    }
    group.phrases[phraseNumber - 1] = [asset.targetText, asset.durationMs];
  }

  return [...groups.values()].map((group) => {
    if (group.phrases.length !== 5 || group.phrases.some((phrase) => !phrase)) {
      throw new Error(`${group.plan} day ${group.day} must contain exactly five runtime audio phrases.`);
    }
    return [group.plan, group.day, group.phrases];
  });
}

export function writePlanRuntimeAudioCompact() {
  const assets = readAuthoringAssets();
  const groups = buildCompactGroups(assets);
  const groupLines = groups.map((group) => `  ${JSON.stringify(group)},`);
  const output =
    '// AUTO-GENERATED by scripts/write_plan_runtime_audio_compact.mjs — do not edit by hand.\n' +
    '// Runtime stores only non-derivable text and duration; ids, paths and approval metadata are reconstructed.\n' +
    'export type RuntimeAudioPhraseRow = readonly [targetText: string, durationMs: number];\n' +
    'export type RuntimeAudioDayGroup = readonly [\n' +
    '  plan: string,\n' +
    '  day: number,\n' +
    '  phrases: readonly RuntimeAudioPhraseRow[],\n' +
    '];\n\n' +
    'export const GENERATED_RUNTIME_AUDIO_GROUPS: readonly RuntimeAudioDayGroup[] = [\n' +
    `${groupLines.join('\n')}\n` +
    '];\n';
  fs.writeFileSync(COMPACT_MANIFEST_PATH, output);
  return { assets: assets.length, groups: groups.length, bytes: Buffer.byteLength(output) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === SCRIPT_PATH) {
  const result = writePlanRuntimeAudioCompact();
  console.log(
    `Compact runtime audio index written: ${result.assets} assets, ${result.groups} day groups, ${result.bytes} bytes.`,
  );
}
